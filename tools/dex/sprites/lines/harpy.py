def _draw(p, view, phase, name):
    legend = {format(i, "x"): color for i, color in enumerate(p.fig.pal.names) if i}
    if view in ("front", "back"):
        path = Path(__file__).resolve().parents[1] / "art" / f"{name.lower()}_{view}{phase}.txt"
        rows = tuple(line[4:] for line in path.read_text().splitlines()
                     if len(line) == 68 and line[:3].strip().isdigit())
        p.fig.patch(0, 0, rows, legend)
        return
    rows = _MINIATURES[name][f"{view}{phase}"]
    width = max(map(len, rows))
    # Native target pixels deliberately ignore fit's design-coordinate transform.
    p.fig.patch((p.W - width) // 2,
                p.H - len(rows) - 1 - (phase if view == "icon" else 0),
                rows, legend)


def harpeck(p, view, phase):
    _draw(p, view, phase, "Harpeck")


def harpelle(p, view, phase):
    _draw(p, view, phase, "Harpelle")


