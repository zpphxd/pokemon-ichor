def legend_kind(mon):
    if "mythical" in mon.roles:
        return "mythical"
    if "box legendary" in mon.roles:
        return "restricted"
    if "legendary trio" in mon.roles or "legendary" in mon.roles:
        return "sub"
    return None


def pics(mon, d):
    e = mon.e
    fr = frames(d / "anim_front.png")
    bb = [bbox(f) for f in fr]
    x0 = min(b[0] for b in bb); x1 = max(b[1] for b in bb)
    y0 = min(b[2] for b in bb); bottom = bb[0][3]
    front = (round8(x1 - x0 + 1), round8(max(b[3] for b in bb) - y0 + 1), 63 - bottom)
    bk = bbox(frames(d / "back.png")[0])
    back = (round8(bk[1] - bk[0] + 1), round8(bk[3] - bk[2] + 1), 63 - bk[3])

    # enemy shadow: under the feet (the bottom rows of frame 0)
    f0 = fr[0]
    feet = np.where((f0[max(0, bottom - 4):bottom + 1] != 0).any(0))[0]
    sx = int(round((feet.min() + feet.max()) / 2 - 32)) if len(feet) else 0
    sy = max(-2, bottom - 50)
    h = e["height_m"]
    ssize = "SHADOW_SIZE_S" if h < 0.9 else "SHADOW_SIZE_M" if h < 1.6 else \
        "SHADOW_SIZE_L" if h < 3.0 else "SHADOW_SIZE_XL_BATTLE_ONLY"

    # Pokédex size comparison: about 41 px per metre at 1x, the trainer ~1.6 m.
    content = max(1, max(b[3] for b in bb) - y0 + 1)
    target = 41 * h
    if target <= content:
        s = target / content
        pscale, poff = int(round(256 / s)), max(0, int(round(60 - (32 + (bottom - 32) * s))))
        tscale, toff = 256, 0
    else:
        st = min(1.0, (1.6 * content / h) / 65)
        pscale, poff = 256, 0
        tscale, toff = min(1600, int(round(256 / st))), int(round((1 - st) * 24))
    return dict(front=front, back=back, shadow=(sx, sy, ssize),
                scale=(pscale, poff, tscale, toff))


