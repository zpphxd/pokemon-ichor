def replace_block(path, begin, end, body, anchor, before=False):
    """Put body between begin/end marker lines; on the first run, add the block
    after (or before) the line that matches anchor."""
    p = ROOT / path
    lines = p.read_text().split("\n")
    block = [begin] + body + [end]
    try:
        i = next(k for k, l in enumerate(lines) if l.strip() == begin.strip())
        j = next(k for k in range(i, len(lines)) if lines[k].strip() == end.strip())
        lines[i:j + 1] = block
    except StopIteration:
        k = next((k for k, l in enumerate(lines) if l.strip() == anchor.strip()), None)
        if k is None:
            raise SystemExit(f"{path}: can't find {anchor!r} to place the Aethos block")
        lines[k if before else k + 1:k if before else k + 1] = block
    write_if_changed(path, "\n".join(lines))


