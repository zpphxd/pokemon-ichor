def sprite_dir(mon):
    d = SPRITES / mon.dir
    if all((d / f).exists() for f in SPRITE_FILES):
        return d
    donor = PLACEHOLDERS.get(mon.name)
    if donor:
        note(f"placeholder art: {mon.name} uses {donor}'s sprites")
        return SPRITES / donor.lower()
    raise SystemExit(f"{mon.name}: no finished sprites in {d} and no placeholder listed")


def copy_sprites(mon):
    src = sprite_dir(mon)
    dst = ROOT / "graphics" / "pokemon" / mon.dir
    dst.mkdir(parents=True, exist_ok=True)
    for f in SPRITE_FILES:
        s, t = src / f, dst / f
        if not t.exists() or not filecmp.cmp(s, t, shallow=False):
            shutil.copyfile(s, t)
    return dst


def read_jasc(path):
    lines = path.read_text().split()
    n = int(lines[2])
    vals = list(map(int, lines[3:3 + 3 * n]))
    return [tuple(vals[i:i + 3]) for i in range(0, len(vals), 3)]


ICON_PALS = [read_jasc(ROOT / f"graphics/pokemon/icon_palettes/pal{i}.pal") for i in range(6)]


def icon_pal_index(d):
    index = SPRITES / "index.json"
    if index.exists():
        pass  # build.py's index is keyed by name; the palette match below is exact anyway
    pal = Image.open(d / "icon.png").getpalette()[:48]
    colors = [tuple(pal[i:i + 3]) for i in range(0, 48, 3)]
    used = set(np.unique(np.array(Image.open(d / "icon.png"))))
    best, best_err = 0, None
    for i, ip in enumerate(ICON_PALS):
        err = sum(sum(abs(a - b) for a, b in zip(colors[k], ip[k])) for k in used if k < len(ip))
        if best_err is None or err < best_err:
            best, best_err = i, err
    if best_err:
        note(f"icon palette for {d.name} matched pal{best} only approximately")
    return best


def frames(path, h=64):
    a = np.array(Image.open(path))
    return [a[i * h:(i + 1) * h] for i in range(a.shape[0] // h)]


def bbox(frame):
    m = frame != 0
    ys, xs = np.where(m.any(1))[0], np.where(m.any(0))[0]
    return int(xs.min()), int(xs.max()), int(ys.min()), int(ys.max())


def round8(n):
    return min(64, max(8, (n + 7) // 8 * 8))


def body_color(d):
    pal = read_jasc(d / "normal.pal")
    f0 = frames(d / "anim_front.png")[0]
    counts = np.bincount(f0.ravel(), minlength=16)
    counts[0] = 0
    scores = {}
    for idx in np.argsort(-counts):
        if counts[idx] == 0:
            break
        r, g, b = (c / 255 for c in pal[idx])
        h, s, v = colorsys.rgb_to_hsv(r, g, b)
        if v < 0.2:
            continue  # outline ink
        if s < 0.18:
            name = "WHITE" if v > 0.8 else "GRAY" if v > 0.35 else "BLACK"
        else:
            deg = h * 360
            if deg < 15 or deg >= 340:
                name = "PINK" if (v > 0.8 and s < 0.5) else "RED"
            elif deg < 45:
                name = "BROWN" if v < 0.75 or s < 0.55 else "RED" if deg < 25 else "YELLOW"
            elif deg < 70:
                name = "YELLOW" if v > 0.6 else "BROWN"
            elif deg < 170:
                name = "GREEN"
            elif deg < 255:
                name = "BLUE"
            elif deg < 300:
                name = "PURPLE"
            else:
                name = "PINK"
        scores[name] = scores.get(name, 0) + int(counts[idx])
    return "BODY_COLOR_" + max(scores, key=scores.get) if scores else "BODY_COLOR_GRAY"


