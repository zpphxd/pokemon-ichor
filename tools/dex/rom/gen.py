def display_names(path, prefix):
    text = path.read_text()
    out = {}
    for const, name in re.findall(
            rf"\[({prefix}\w+)\]\s*=\s*\{{\s*\.name\s*=\s*(?:COMPOUND_STRING|_|ITEM_NAME)\(\"([^\"]+)\"\)", text):
        out.setdefault(name, const)
    return out


def engine_tables():
    moves = display_names(ROOT / "src/data/moves_info.h", "MOVE_")
    abilities = display_names(ROOT / "src/data/abilities.h", "ABILITY_")
    items = set(re.findall(r"^\s*(ITEM_\w+)\b", (ROOT / "include/constants/items.h").read_text(), re.M))
    cries = set(re.findall(r"^\s*(CRY_\w+)\b", (ROOT / "include/constants/cries.h").read_text(), re.M))
    mapsecs = set(re.findall(r'"id":\s*"(MAPSEC_\w+)"',
                             (ROOT / "src/data/region_map/region_map_sections.json").read_text()))
    return moves, abilities, items, cries, mapsecs


MOVES, ABILITIES, ITEMS, CRY_IDS, MAPSECS = engine_tables()


def move_const(name, where):
    if name not in MOVES:
        raise SystemExit(f"{where}: unknown move {name!r}")
    return MOVES[name]


def ability_const(name, where):
    if name not in ABILITIES:
        raise SystemExit(f"{where}: unknown ability {name!r}")
    return ABILITIES[name]


def item_const(name, where):
    const = "ITEM_" + re.sub(r"[^A-Z0-9]+", "_", name.upper()).strip("_")
    if const not in ITEMS:
        raise SystemExit(f"{where}: unknown item {name!r} ({const})")
    return const


