def enum_value(path, const):
    """Value of an enum constant, reading the header's enum lines in order."""
    vals, val = {}, -1
    for raw in (ROOT / path).read_text().split("\n"):
        m = re.match(r"\s*((?:SPECIES|NATIONAL_DEX)_\w+)\s*(?:=\s*(\w+))?\s*,", raw)
        if not m:
            continue
        if m.group(2):
            v = int(m.group(2)) if m.group(2).isdigit() else vals.get(m.group(2))
            if v is None:
                continue  # an alias of something later; not needed here
            val = v
        else:
            val += 1
        vals[m.group(1)] = val
        if m.group(1) == const:
            return val
    raise SystemExit(f"{path}: no {const}")


