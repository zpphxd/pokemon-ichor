def vanilla_dex_keys():
    keys = {}
    for f in sorted((ROOT / "src/data/pokemon/species_info").glob("gen_*_families.h")):
        text = f.read_text()
        for block in re.split(r"\n    \[SPECIES_\w+\]\s*=", text)[1:]:
            nat = re.search(r"\.natDexNum\s*=\s*(NATIONAL_DEX_\w+)", block)
            if not nat or nat.group(1) in keys:
                continue
            name = re.search(r'\.speciesName\s*=\s*_\("([^"]+)"\)', block)
            h = re.search(r"\.height\s*=\s*(\d+)\s*,", block)
            w = re.search(r"\.weight\s*=\s*(\d+)\s*,", block)
            keys[nat.group(1)] = (name.group(1).upper() if name else None,
                                  int(h.group(1)) if h else None, int(w.group(1)) if w else None)
    return keys


def gen_dex_orders(mons):
    path = ROOT / "src/data/pokemon/pokedex_orders.h"
    text = path.read_text()
    tag = " // Aethos"
    text = "\n".join(l for l in text.split("\n") if not l.endswith(tag))
    vk = vanilla_dex_keys()
    ours = {m.nat: (m.name.upper(), int(round(m.e["height_m"] * 10)), int(round(m.e["weight_kg"] * 10)))
            for m in mons}

    def merge(array, field):
        nonlocal text
        m = re.search(rf"(const u16 {array}\[\] =\n\{{\n)(.*?)(\n\}};)", text, re.S)
        lines = m.group(2).split("\n")
        entries = [re.match(r"\s*(NATIONAL_DEX_\w+),", l) for l in lines]
        add = sorted(ours, key=lambda n: (ours[n][field], n))
        out, ai = [], 0
        for l, en in zip(lines, entries):
            key = vk.get(en.group(1), (None,) * 3)[field] if en else None
            while ai < len(add) and key is not None and ours[add[ai]][field] < key:
                out.append(f"    {add[ai]},{tag}")
                ai += 1
            out.append(l)
        out += [f"    {n},{tag}" for n in add[ai:]]
        text = text[:m.start(2)] + "\n".join(out) + text[m.end(2):]

    merge("gPokedexOrder_Alphabetical", 0)
    merge("gPokedexOrder_Weight", 2)
    merge("gPokedexOrder_Height", 1)
    write_if_changed("src/data/pokemon/pokedex_orders.h", text)


