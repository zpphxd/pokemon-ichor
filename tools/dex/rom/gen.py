class Mon:
    pass


def load_species():
    plan = yaml.safe_load((DESIGN / "plan.yaml").read_text())
    by_line = {}
    for f in sorted((DESIGN / "species").glob("*.yaml")):
        d = yaml.safe_load(f.read_text())
        by_line[d["line"]] = d["species"]
    mons = []
    for line in plan["lines"]:
        lid = line["id"]
        entries = sorted(by_line[lid], key=lambda s: s["dex"])
        members = line["members"]
        if len(entries) != len(members):
            raise SystemExit(f"{lid}: plan has {len(members)} members, YAML has {len(entries)}")
        line_mons = []
        for i, (e, m) in enumerate(zip(entries, members)):
            mon = Mon()
            mon.e, mon.member, mon.line, mon.index = e, m, lid, i
            mon.roles = line.get("roles", [])
            mon.name = e["name"]
            if not re.fullmatch(r"[A-Z][a-z]+", mon.name):
                raise SystemExit(f"{mon.name}: names must be one capitalized word")
            mon.const = "SPECIES_" + mon.name.upper()
            mon.nat = "NATIONAL_DEX_" + mon.name.upper()
            mon.dir = mon.name.lower()
            mon.line_size = len(members)
            line_mons.append(mon)
        for mon in line_mons:
            mon.line_mons = line_mons
        mons.extend(line_mons)
    mons.sort(key=lambda m: m.e["dex"])
    nums = [m.e["dex"] for m in mons]
    if nums != list(range(1, len(mons) + 1)):
        raise SystemExit("dex numbers must run 1..N without gaps")
    # stage: 0 for first stages, 1 middle, 2 final (single-stage species count as final)
    for m in mons:
        pre = [o for o in m.line_mons if evo_targets(o, m)]
        m.prevo = pre[0] if pre else None
    for m in mons:
        depth, p = 0, m.prevo
        while p:
            depth, p = depth + 1, p.prevo
        m.depth = depth
        m.evolves = bool(evos_of(m))
        m.is_final = not m.evolves
    return mons


def evos_of(mon):
    evo = mon.member.get("evo")
    if not evo:
        return []
    evo = evo if isinstance(evo, list) else [evo]
    out = []
    for e in evo:
        to = e.get("to", mon.index + 1)
        out.append((e, mon.line_mons[to]))
    return out


def evo_targets(mon, target):
    return any(t is target for _, t in evos_of(mon))


