#!/usr/bin/env python3
"""Resolve the conflicts a batch agent's merge leaves in Act II's shared files.

  python3 tools/ichor/act2/merge/resolve.py THEIRS_BRANCH   (from the repo root, mid-merge)

- flags.h: per conflict block, vanilla `#define NAME 0xVAL` lines are merged by value
  (a named claim beats FLAG_UNUSED_), every other line is the union of both sides in order.
- layouts.json / heal_locations.json: merged by id (theirs wins on an id both changed).
- trainers.party, opponents.h: ours (they are regenerated by fold_parties.py afterwards).
- ORDER.txt and any other text file: union of both sides, ours first, no duplicate lines.
- C tables whose theirs-side changes are pure additions: grafted (graft.py).
Prints what it did; leaves a file conflicted if it can't.
"""
import json, re, subprocess, sys
from pathlib import Path

THEIRS = sys.argv[1]
SCR = Path(__file__).parent   # graft.py lives beside this file
def git(*a): return subprocess.run(['git', *a], capture_output=True, text=True).stdout
files = git('diff', '--name-only', '--diff-filter=U').split()
base = git('merge-base', 'HEAD', THEIRS).strip()
BLOCK = re.compile(r'^<<<<<<< [^\n]*\n(.*?)^=======\n(.*?)^>>>>>>> [^\n]*\n', re.S | re.M)

def union_lines(ours, theirs):
    out = ours.split('\n')
    seen = set(l for l in out if l.strip())
    for l in theirs.split('\n'):
        if l.strip() and l in seen: continue
        out.append(l); seen.add(l)
    return '\n'.join(x for x in out if x != '' or True).rstrip('\n') + '\n'

VAN = re.compile(r'^#define (FLAG_\w+)\s+(0x[0-9A-Fa-f]+)\b')
def merge_flags_block(ours, theirs):
    o, t = ours.split('\n'), theirs.split('\n')
    if any(VAN.match(l) for l in o + t):
        byval, order = {}, []
        rest = []
        for l in o + t:
            m = VAN.match(l)
            if not m:
                if l.strip() and l not in rest: rest.append(l)
                continue
            v = int(m.group(2), 16)
            if v not in byval: order.append(v)
            if v not in byval or byval[v][0].startswith('FLAG_UNUSED'):
                byval[v] = (m.group(1), l)
        lines = [byval[v][1] for v in sorted(order)] + rest
        return '\n'.join(lines) + '\n'
    return union_lines(ours.rstrip('\n'), theirs.rstrip('\n'))

for f in files:
    p = Path(f)
    if p.name in ('trainers.party', 'opponents.h'):
        git('checkout', '--ours', f); print(f, 'ours (refold later)'); continue
    if p.suffix == '.json' and p.name in ('layouts.json', 'heal_locations.json'):
        o = json.loads(git('show', f'HEAD:{f}')); t = json.loads(git('show', f'{THEIRS}:{f}'))
        b = json.loads(git('show', f'{base}:{f}'))
        key = 'layouts' if 'layouts' in o else 'heal_locations'
        def idx(d): return {x.get('id'): x for x in d[key] if isinstance(x, dict)}
        bo, oo, to = idx(b), idx(o), idx(t)
        merged = list(o[key])
        pos = {x.get('id'): i for i, x in enumerate(merged) if isinstance(x, dict)}
        for i, x in to.items():
            if i in pos:
                if x != bo.get(i) and x != oo[i]: merged[pos[i]] = x   # theirs changed it
            else:
                merged.append(x)
        o[key] = merged
        p.write_text(json.dumps(o, indent=2, ensure_ascii=False) + '\n'); print(f, 'json merged'); continue
    if (p.suffix == '.json' and p.name not in ('layouts.json', 'heal_locations.json')) or p.name in ('species.h',):
        print(f, 'LEFT for hand merge (jsonmerge.py for map_groups/wild_encounters)'); continue
    s = p.read_text()
    if p.name == 'flags.h':
        s = BLOCK.sub(lambda m: merge_flags_block(m.group(1), m.group(2)), s)
    elif p.suffix in ('.h', '.c') and f.startswith(('src/data/tilesets', 'src/data/object_events', 'include/constants/event_objects', 'include/constants/metatile_labels', 'include/constants/trainers', 'src/battle_main', 'src/data/graphics', 'src/data/trade', 'include/constants/trade', 'src/data/ichor_herms', 'include/constants/ichor_herms', 'src/tileset_anims')):
        r = subprocess.run(['python3', str(SCR / 'graft.py'), base, THEIRS, f], capture_output=True, text=True)
        print(r.stdout.strip() or r.stderr.strip().splitlines()[-1]); continue
    else:
        s = BLOCK.sub(lambda m: union_lines(m.group(1).rstrip('\n'), m.group(2).rstrip('\n')), s)
    p.write_text(s); print(f, 'unioned')

left = [f for f in files if '<<<<<<<' in Path(f).read_text()]
print('still conflicted:', left)
