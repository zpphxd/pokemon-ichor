def mon_text(sp, lvl, moves, item=None, ability=None, nature=None, evs=None, ivs="20"):
    out = [f"{sp} @ {item}" if item else sp, f"Level: {lvl}"]
    if ability:
        out.append(f"Ability: {ability}")
    out.append(f"IVs: {ivs} HP / {ivs} Atk / {ivs} Def / {ivs} SpA / {ivs} SpD / {ivs} Spe")
    if evs:
        out.append(f"EVs: {evs}")
    if nature:
        out.append(f"{nature} Nature")
    out += [f"- {m}" for m in moves]
    return "\n".join(out)


def header(const, name, cls, pic, gender, music, difficulty=None, ai="Basic Trainer", mugshot=None, status=None):
    h = [f"=== TRAINER_ICHOR_{const} ===", f"Name: {name}", f"Class: {cls}", f"Pic: {pic}",
         f"Gender: {gender}", f"Music: {music}"]
    if difficulty:
        h.append(f"Difficulty: {difficulty}")
    h.append(f"AI: {ai}")
    if mugshot:
        h.append(f"Mugshot: {mugshot}")
    if status:
        h.append(f"Starting Status: {status}")
    return "\n".join(h)


def build():
    parts = [START, ""]
    for const, name, cls, pic, gender, music, ai, party in ASCENT:
        parts.append(header(const, name, cls, pic, gender, music, ai=ai))
        parts.append("")
        for sp, lvl, item, moves in party:
            parts.append(mon_text(sp, lvl, moves, item, ivs="24" if ai == SMART else "20"))
            parts.append("")
    for const, name, cls, pic, gender, music, mug, status, party in BOSSES:
        # Hero: held items, natures and a lighter spread, smart AI
        parts.append(header(const, name, cls, pic, gender, music, ai="Smart Trainer", mugshot=mug, status=status))
        parts.append("")
        for sp, lvl, item, ability, nature, evs, moves in party:
            parts.append(mon_text(sp, lvl, moves, item, ability, nature, HERO_EVS[evs], ivs="26"))
            parts.append("")
        # Mortal: Hero's species and moves, three levels lower
        parts.append(header(const, name, cls, pic, gender, music, "Easy", mugshot=mug))
        parts.append("")
        for sp, lvl, item, ability, nature, evs, moves in party:
            parts.append(mon_text(sp, lvl - 3, moves, None, ability))
            parts.append("")
        # Spartan: full spreads and natures, smart AI
        parts.append(header(const, name, cls, pic, gender, music, "Hard", "Smart Trainer", mugshot=mug, status=status))
        parts.append("")
        for sp, lvl, item, ability, nature, evs, moves in party:
            parts.append(mon_text(sp, lvl, moves, item, ability, nature, evs, ivs="31"))
            parts.append("")
    parts.append(END)
    return "\n".join(parts) + "\n"


def main():
    import re
    text = PATH.read_text()
    block = build()
    # every earlier copy of the block, whatever ids its header named
    marks = [m.start() for m in re.finditer(r"/\* Ichor: the League \(ids 460-\d+\)", text)]
    if marks:
        first = marks[0]
        for a in reversed(marks):
            b = text.index(END, a) + len(END) + 1
            text = text[:a] + text[b:]
        text = text[:first] + block + text[first:]
    else:
        text = text.rstrip("\n") + "\n\n" + block
    PATH.write_text(text)


if __name__ == "__main__":
    main()
