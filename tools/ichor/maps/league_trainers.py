def mon_text(sp, lvl, moves, item=None, ability=None, nature=None, evs=None, ivs="20"):
    out = [f"{sp} @ {item}" if item else sp, f"Level: {lvl}"]
    if ability:
        out.append(f"Ability: {ability}")
    out.append(f"IVs: {ivs} HP / {ivs} Atk / {ivs} Def / {ivs} SpA / {ivs} SpD / {ivs} Spe")
    if evs:
        out.append(f"EVs: {evs}")
    if nature:
        out.append(f"{nature} Nature")
    out += [f"- {m}" for m in moves]
    return "\n".join(out)


def header(const, name, cls, pic, gender, music, difficulty=None, ai="Basic Trainer"):
    h = [f"=== TRAINER_ICHOR_{const} ===", f"Name: {name}", f"Class: {cls}", f"Pic: {pic}",
         f"Gender: {gender}", f"Music: {music}"]
    if difficulty:
        h.append(f"Difficulty: {difficulty}")
    h.append(f"AI: {ai}")
    return "\n".join(h)


def build():
    parts = [START, ""]
    for const, name, cls, pic, gender, music, party in ASCENT:
        parts.append(header(const, name, cls, pic, gender, music))
        parts.append("")
        for sp, lvl, item, moves in party:
            parts.append(mon_text(sp, lvl, moves, item))
            parts.append("")
    for const, name, cls, pic, gender, music, party in BOSSES:
        # Hero: held items, no spreads
        parts.append(header(const, name, cls, pic, gender, music, ai="Smart Trainer"))
        parts.append("")
        for sp, lvl, item, ability, nature, evs, moves in party:
            parts.append(mon_text(sp, lvl, moves, item, ability, ivs="24"))
            parts.append("")
        # Mortal: Hero's species and moves, three levels lower
        parts.append(header(const, name, cls, pic, gender, music, "Easy"))
        parts.append("")
        for sp, lvl, item, ability, nature, evs, moves in party:
            parts.append(mon_text(sp, lvl - 3, moves, None, ability))
            parts.append("")
        # Spartan: trained spreads and natures, smart AI
        parts.append(header(const, name, cls, pic, gender, music, "Hard", "Smart Trainer"))
        parts.append("")
        for sp, lvl, item, ability, nature, evs, moves in party:
            parts.append(mon_text(sp, lvl, moves, item, ability, nature, evs, ivs="31"))
            parts.append("")
    parts.append(END)
    return "\n".join(parts) + "\n"


def main():
    text = PATH.read_text()
    block = build()
    if START in text:
        a = text.index(START)
        b = text.index(END) + len(END) + 1
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n" + block
    PATH.write_text(text)


if __name__ == "__main__":
    main()
