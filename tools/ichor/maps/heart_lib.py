"""Shared builder for the Labyrinth's heart (Rings V-VII, their rooms, the Starry
Chamber, the Icarus Shaft): design/LABYRINTH.md, design/LABYRINTH_MAZE.md.

A HeartMap is drawn as terrain on a character grid, then autotiled:

  R  cave rock (cave_dark_kit's rock with depth: tops, rims, two-row flowstone faces)
  M  the house's masonry (the corridor kit's tops and one-row faces)
  .  cave floor (threadable, MB_CAVE: wild Pokémon)     ,  the house's slabs (threadable, quiet)
  o  sunlit floor under a skylight (MB_ICHOR_LIGHT_POOL) m  starlit marble (astra)
  ~  still water (Surf)    L  magma    P  a pit or chasm    V  void

Pieces (stalagmites, the bell, the forge...) go on top by key and part name from
tools/ichor/maps/mychos_tiles.py, the catalog tools/ichor/art/mychos_build.py writes.
Each map's ON_LOAD gets a generated block registering its thread floors and anchors.
graph_stats() measures LABYRINTH_MAZE.md §2's rules on the floor plan.
"""
