# The house's corridor kit: an autotile over wall/floor (labyrinth_tiles.classify)
# --------------------------------------------------------------------------

def _top_name(n, w, e, inner):
    sides = "".join(c for c, v in (("n", n), ("w", w), ("e", e)) if v)
    name = "top" + (f"_{sides}" if sides else "")
    if inner:
        name += "_in_" + "_".join(inner)
    return name


def _face_name(left, right):
    short = {"open": "o", "cont": "c", "inner": "i"}
    return f"face_{short[left]}{short[right]}"


def house_classify(wall, x, y):
    if not wall(x, y + 1):
        def end(dx):
            if not wall(x + dx, y):
                return "open"
            if wall(x + dx, y + 1):
                return "inner"
            return "cont"
        return _face_name(end(-1), end(1))
    n, w, e = not wall(x, y - 1), not wall(x - 1, y), not wall(x + 1, y)
    inner = []
    if not n and not w and not wall(x - 1, y - 1):
        inner.append("nw")
    if not n and not e and not wall(x + 1, y - 1):
        inner.append("ne")
    if not w and not wall(x - 1, y + 1):
        inner.append("sw")
    if not e and not wall(x + 1, y + 1):
        inner.append("se")
    return _top_name(int(n), int(w), int(e), tuple(inner))


