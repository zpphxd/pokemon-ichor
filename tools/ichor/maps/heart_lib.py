class HeartMap(KM.Map):
    def __init__(self, name, ts, w, h):
        self.name, self.ts, self.w, self.h, self.primary = name, ts, w, h, "oikos"
        self.catalog = MT.CATALOG[ts]
        self.P = self.catalog["pieces"]
        self.cat = {"symbol": SYMBOL[ts]}
        self.mid = np.zeros((h, w), np.uint16)
        self.solid = np.ones((h, w), bool)
        self.pattr = KM._attrs("data/tilesets/primary/oikos/porytiles_bin/metatile_attributes.bin")
        self.sattr = KM._attrs(f"data/tilesets/secondary/{ts}/porytiles_bin/metatile_attributes.bin")
        self.objects, self.warps, self.coords, self.bgs, self.connections = [], [], [], [], []
        self.seams = []
        self.border = [self.pid("void", "void")] * 4 if "void" in self.P else [0x200] * 4
        self.header = {}
        self.forced_open = set()
        self.t = [["R"] * w for _ in range(h)]
        self.anchors = []        # (x, y, THREAD_ANCHOR_*)
        self.cracks = []         # (x, y, flag)
        self.gen = []            # extra generated ON_LOAD lines
        self.deco = {}           # (x, y) -> (mid, solid) placed after the autotile
        self.notes = {}          # (x, y) -> label, for the graph
        self.nothread = set()

    # --- terrain ----------------------------------------------------------------------------
    def T(self, x, y):
        if not (0 <= x < self.w and 0 <= y < self.h):
            return "R"
        return self.t[y][x]

    def carve(self, x0, y0, x1, y1, ch="."):
        for y in range(min(y0, y1), max(y0, y1) + 1):
            for x in range(min(x0, x1), max(x0, x1) + 1):
                if 0 <= x < self.w and 0 <= y < self.h:
                    self.t[y][x] = ch

    def cell(self, x, y, ch):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.t[y][x] = ch

    def draw(self, rows, ox=0, oy=0, legend=None):
        """Paint an ASCII block; ' ' leaves the cell as it is."""
        for j, row in enumerate(rows):
            for i, ch in enumerate(row):
                if ch == " ":
                    continue
                self.cell(ox + i, oy + j, (legend or {}).get(ch, ch))

    def walkable_t(self, x, y):
        return self.T(x, y) in FLOORS

    # --- pieces -------------------------------------------------------------------------------
    def pid(self, key, part):
        p = self.P[key]
        cx, cy = p["names"].get(part, (0, 0))
        return p["ids"][cy][cx]

    def pwalk(self, key, part):
        p = self.P[key]
        cx, cy = p["names"].get(part, (0, 0))
        return p["walk"][cy][cx]

    def place(self, x, y, key, part, solid=None):
        mid = self.pid(key, part)
        if solid is None:
            solid = self.pwalk(key, part) in "X"
        self.deco[(x, y)] = (mid, solid)

    def place_block(self, x, y, key, odd_twin=True):
        """A whole piece with its top-left at (x, y), by floor parity if it has an odd twin."""
        k = key
        if odd_twin and (x + y) % 2 == 1 and key + "_odd" in self.P:
            k = key + "_odd"
        p = self.P[key]
        q = self.P[k]
        r0 = (q.get("twin_of") or [key, 0])[1] if k != key else 0
        for cy in range(p["h"]):
            for cx in range(p["w"]):
                src = q if (k != key and r0 <= cy < r0 + q["h"]) else p
                sy = cy - r0 if src is q and k != key else cy
                mid = src["ids"][sy][cx]
                self.deco[(x + cx, y + cy)] = (mid, src["walk"][sy][cx] == "X")

    # --- the autotile --------------------------------------------------------------------------
    def lay(self):
        cave_grid = ["".join("#" if self.T(x, y) in "RM" else "~" if self.T(x, y) == "~" else "."
                             for x in range(self.w)) for y in range(self.h)]
        kinds = kit.classify(cave_grid)
        magma_grid = ["".join("#" if self.T(x, y) in "RM" else "~" if self.T(x, y) == "L" else "."
                              for x in range(self.w)) for y in range(self.h)]
        mk = kit.classify(magma_grid)
        pit_grid = ["".join("#" if self.T(x, y) in "RM" else "~" if self.T(x, y) == "P" else "."
                            for x in range(self.w)) for y in range(self.h)]
        pk = kit.classify(pit_grid)
        wall = lambda x, y: self.T(x, y) in SOLIDS
        cat_kit = {"kit": self.catalog["kit"]}
        cave_floor = self.pid("cave", "cave")
        sun = self.pid("sun", "sun") if "sun" in self.P else cave_floor
        for y in range(self.h):
            for x in range(self.w):
                ch = self.T(x, y)
                if ch == "R":
                    key = kit.cell_key(cave_grid, kinds, x, y)
                    mid = kit.kit_id(cat_kit, key)
                    # dripstone and flowstone now and then on long faces
                    if key.startswith(("ft|", "fb|")) and key.split("|")[1] in "ABCD" and key.split("|")[2] in "ABCD":
                        hh = kit.h("drip", x, y // 2) % 9
                        if hh == 0:
                            mid = self.pid("formations", "drip_ft" if key[:2] == "ft" else "drip_fb")
                        elif hh == 1 and self.T(x, y + (1 if key[:2] == "ft" else 0)) == "R":
                            mid = self.pid("formations", "flow_ft" if key[:2] == "ft" else "flow_fb")
                    self.set(x, y, mid, True)
                elif ch == "M":
                    self.set(x, y, self.pid("walls", house_classify(wall, x, y)), True)
                elif ch == ",":
                    self.set(x, y, self.pid("thread", "dark_l" if (x + y) % 2 == 0 else "dark_r"), False)
                elif ch == ".":
                    self.set(x, y, cave_floor, False)
                elif ch == "o":
                    self.set(x, y, sun, False)
                elif ch == "m":
                    self.set(x, y, self.pid("marble", "marble"), False)
                elif ch == "x":
                    self.set(x, y, cave_floor, False)
                elif ch == "~":
                    key = kit.cell_key(cave_grid, kinds, x, y)
                    self.set(x, y, kit.kit_id({"kit": self.catalog["water"]}, key), False)
                elif ch == "L":
                    key = kit.cell_key(magma_grid, mk, x, y)
                    self.set(x, y, kit.kit_id({"kit": self.catalog["magma"]}, key), True)
                elif ch == "P":
                    key = kit.cell_key(pit_grid, pk, x, y)
                    self.set(x, y, kit.kit_id({"kit": self.catalog["pit"]}, key), True)
                else:
                    self.set(x, y, self.pid("void", "void"), True)
        for (x, y), (mid, solid) in self.deco.items():
            self.set(x, y, mid, solid)

    # --- the Labyrinth's registrations ----------------------------------------------------------
    def anchor(self, x, y, name):
        self.place(x, y, "anchor", "ring", solid=False)
        if (x + y) % 2:
            self.deco[(x, y)] = (self.P["anchor_odd"]["ids"][0][0], False)
        self.anchors.append((x, y, name))

    def crack(self, x, y, flag):
        """A cracked house wall Asterion can break; it breaks to cave floor."""
        self.cell(x, y, "M")
        self.deco[(x, y)] = (self.pid("formations", "cracked"), True)
        self.cracks.append((x, y, flag))

    def thread_floors(self):
        out = []
        for key, base in (("thread", "dark_l"), ("thread", "dark_r"), ("cave", "cave"), ("sun", "sun"),
                          ("marble", "marble")):
            if key in self.P and base in self.P[key]["names"]:
                f = self.pid(key, base)
                out.append((f, f + 1))
        return out

    def onload_block(self):
        lines = [GEN_BEGIN]
        for f, twin in self.thread_floors():
            lines += [f"    setvar(VAR_0x8004, 0x{f:03X})", f"    setvar(VAR_0x8005, 0x{twin:03X})",
                      "    special(Ichor_AddThreadFloor)"]
        for x, y, name in self.anchors:
            lines += [f"    setvar(VAR_0x8004, {x})", f"    setvar(VAR_0x8005, {y})",
                      f"    setvar(VAR_0x8006, {name})", "    special(Ichor_AddThreadAnchor)"]
        cave = self.pid("cave", "cave")
        for x, y, flag in self.cracks:
            lines += [f"    setvar(VAR_0x8004, {x})", f"    setvar(VAR_0x8005, {y})",
                      f"    setvar(VAR_0x8006, {flag})", f"    setvar(VAR_0x8007, 0x{cave:03X})",
                      "    special(Ichor_AddCrackedWall)",
                      f"    if (flag({flag})) {{ setmetatile({x}, {y}, 0x{cave:03X}, FALSE) }}"]
        lines += ["    " + g for g in self.gen]
        lines.append("    " + GEN_END)
        return "\n".join(lines)

    def write_generated(self):
        p = ROOT / "data/maps" / self.name / "scripts.pory"
        text = p.read_text()
        block = self.onload_block()
        if GEN_BEGIN in text:
            text = re.sub(re.escape(GEN_BEGIN) + r".*?" + re.escape(GEN_END), block.strip(), text, flags=re.S)
        else:
            raise SystemExit(f"{p}: put the GENERATED markers in its ON_LOAD script first")
        p.write_text(text)

    # --- LABYRINTH_MAZE.md §2: measuring the maze ------------------------------------------------
    def graph_stats(self, region=None):
        """Junctions, dead ends, loops and the longest featureless straight run, on the
        walkable cells (in `region`, a set of cells, if given)."""
        cells = {(x, y) for y in range(self.h) for x in range(self.w)
                 if self.walkable_t(x, y) and (region is None or (x, y) in region)}
        for (x, y), (mid, solid) in self.deco.items():
            if solid:
                cells.discard((x, y))

        def nb(c):
            x, y = c
            return [(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)) if (x + dx, y + dy) in cells]

        # corridor cells: a cell is "in a room" if it sits in a 2x2 of floor
        def roomy(c):
            x, y = c
            for dx in (0, -1):
                for dy in (0, -1):
                    if all((x + dx + i, y + dy + j) in cells for i in (0, 1) for j in (0, 1)):
                        return True
            return False
        junctions = [c for c in cells if len(nb(c)) >= 3 and not roomy(c)]
        dead = [c for c in cells if len(nb(c)) == 1]
        # loops: independent cycles of the cell graph, counted on corridors only (rooms collapse)
        comp_seen, comps = set(), 0
        for c in cells:
            if c in comp_seen:
                continue
            comps += 1
            q = deque([c])
            comp_seen.add(c)
            while q:
                u = q.popleft()
                for v in nb(u):
                    if v not in comp_seen:
                        comp_seen.add(v)
                        q.append(v)
        corr = {c for c in cells if not roomy(c)}
        edges = sum(1 for c in corr for v in nb(c) if v in corr and v > c)
        cseen, ccomps = set(), 0
        for c in corr:
            if c in cseen:
                continue
            ccomps += 1
            q = deque([c])
            cseen.add(c)
            while q:
                u = q.popleft()
                for v in nb(u):
                    if v in corr and v not in cseen:
                        cseen.add(v)
                        q.append(v)
        loops = edges - len(corr) + ccomps
        featured = set(self.notes) | {(x, y) for x, y, _ in self.anchors} | {(o["x"], o["y"]) for o in self.objects}
        longest, where = 0, None
        for c in corr:
            for dx, dy in ((1, 0), (0, 1)):
                if (c[0] - dx, c[1] - dy) in corr:
                    continue
                run, cur = 0, c
                while cur in corr:
                    run += 1
                    side = [(cur[0] + dy, cur[1] + dx), (cur[0] - dy, cur[1] - dx)]
                    if any(s in cells for s in side) or cur in featured:
                        if run > longest:
                            longest, where = run, cur
                        run = 0
                    cur = (cur[0] + dx, cur[1] + dy)
                if run > longest:
                    longest, where = run, cur
        screens = self.w * self.h / 150
        return {"walkable": len(cells), "junctions": len(junctions), "per_screen": round(len(junctions) / screens, 1),
                "dead_ends": len(dead), "dead_cells": sorted(dead), "loops": loops, "longest_run": longest, "longest_at": where,
                "components": comps}

    def ascii(self):
        return "\n".join("".join(r) for r in self.t)
