FLOORS = ".,omx"          # walkable terrain (x: a floor that takes no thread, e.g. under a scene)
SOLIDS = "RMV"
GEN_BEGIN = "// ---- BEGIN GENERATED by tools/ichor/maps/labyrinth_heart.py: do not edit ----"
GEN_END = "// ---- END GENERATED ----"
SYMBOL = {"mychos": "gTileset_Mychos", "astra": "gTileset_Astra"}


def const_name(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).upper()


def ensure_map(name, w, h, ts, music, mapsec="MAPSEC_PALACE_OF_MINOS", group="gMapGroup_Labyrinth",
               map_type="MAP_TYPE_UNDERGROUND", show_name=False):
    """Register the map and its layout if they don't exist yet (as tools/ichor/new_map.py)."""
    lp = ROOT / "data/layouts/layouts.json"
    lay = json.loads(lp.read_text())
    lid = "LAYOUT_" + const_name(name)
    if not any(l.get("id") == lid for l in lay["layouts"]):
        d = ROOT / "data/layouts" / name
        d.mkdir(parents=True, exist_ok=True)
        np.zeros(w * h, "<u2").tofile(d / "map.bin")
        np.zeros(4, "<u2").tofile(d / "border.bin")
        lay["layouts"].append({"id": lid, "name": f"{name}_Layout", "width": w, "height": h,
                               "primary_tileset": "gTileset_Oikos", "secondary_tileset": SYMBOL[ts],
                               "border_filepath": f"data/layouts/{name}/border.bin",
                               "blockdata_filepath": f"data/layouts/{name}/map.bin",
                               "layout_version": "emerald"})
        lp.write_text(json.dumps(lay, indent=2, ensure_ascii=False) + "\n")
    md = ROOT / "data/maps" / name
    if not (md / "map.json").exists():
        md.mkdir(parents=True, exist_ok=True)
        (md / "map.json").write_text(json.dumps({
            "id": "MAP_" + const_name(name), "name": name, "layout": lid, "music": music,
            "region": "REGION_HOENN", "region_map_section": mapsec, "requires_flash": False,
            "weather": "WEATHER_NONE", "map_type": map_type, "allow_cycling": False,
            "allow_escaping": False, "allow_running": True, "show_map_name": show_name,
            "battle_scene": "MAP_BATTLE_SCENE_NORMAL", "connections": None, "object_events": [],
            "warp_events": [], "coord_events": [], "bg_events": []}, indent=2) + "\n")
        if not (md / "scripts.pory").exists():
            (md / "scripts.pory").write_text(f"mapscripts {name}_MapScripts {{}}\n")
        gi = ROOT / ".gitignore"
        line = f"data/maps/{name}/scripts.inc"
        if line not in gi.read_text().split("\n"):
            with gi.open("a") as f:
                f.write(line + "\n")
        gp = ROOT / "data/maps/map_groups.json"
        groups = json.loads(gp.read_text())
        if group not in groups:
            groups[group] = []
            groups["group_order"].append(group)
        if name not in groups[group]:
            groups[group].append(name)
        gp.write_text(json.dumps(groups, indent=2, ensure_ascii=False) + "\n")
        inc = ROOT / "data/ichor_maps.inc"
        text = inc.read_text()
        if f"data/maps/{name}/scripts.inc" not in text:
            with inc.open("a") as f:
                f.write(f'\t.include "data/maps/{name}/scripts.inc"\n')


