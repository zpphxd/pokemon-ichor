# ---------------------------------------------------------------------------
DW, DH = 34, 28


def build_deep(PLANS):
    r = plan(DW, DH)
    blob(r, ".", 8, 5, 5, 3, salt=11)            # under the ladder
    carve(r, ".", 6, 8, 9, 12)
    blob(r, ".", 16, 16, 14, 9, salt=12)         # the tarn's chamber
    blob(r, "~", 17, 16, 9, 5, salt=13, rough=0.1)
    blob(r, ".", 17, 16, 2, 1, salt=14, rough=0.0)   # the island
    blob(r, ".", 29, 15, 3, 4, salt=15)          # the far shore
    blob(r, ".", 24, 5, 5, 3, salt=16)           # the drowned shrine's niche
    carve(r, ".", 15, 7, 20, 8)
    carve(r, ".", 19, 4, 20, 8)
    # the meltwater fall (2026-11-18): a channel from the tarn north to a fall that
    # the cold never stopped; the Horn of Achelous climbs it to a pool and a ledge
    carve(r, "#", 13, 0, 18, 6)
    carve(r, "~", 15, 7, 16, 10)
    carve(r, "~", 14, 2, 17, 3)
    carve(r, ".", 14, 1, 17, 1)
    g = Snow("Ascent_IcefallDeep", r)
    P = "Ascent_IcefallDeep_EventScript_"
    g.put("ladder_up", 8, 4)
    g.warp(8, 4, "Ascent_Icefall", 6)
    g.item("ITEM_TM_HYPER_BEAM", 17, 16, "FLAG_ICHOR_ITEM_DEEP_TM_HYPER_BEAM")
    g.put("meltfall", 15, 4)
    for y in (4, 5, 6):
        for x in (15, 16):
            g.solid[y, x], g.water[y, x] = False, True
    g.item("ITEM_ASSAULT_VEST", 16, 1, "FLAG_ICHOR_ITEM_DEEP_ASSAULT_VEST")
    g.hidden("ITEM_RELIC_GOLD", 14, 1, "FLAG_ICHOR_HIDDEN_ITEM_DEEP_RELIC_GOLD")
    g.sign(17, 6, P + "Meltfall", facing="NORTH")
    g.put("shrine", 25, 3)
    g.sign(25, 4, P + "Styx")
    g.item("ITEM_SPELL_TAG", 27, 6, "FLAG_ICHOR_ITEM_DEEP_SPELL_TAG")
    g.hidden("ITEM_PEARL_STRING", 30, 16, "FLAG_ICHOR_HIDDEN_ITEM_DEEP_PEARL_STRING")
    g.hidden("ITEM_BIG_PEARL", 26, 4, "FLAG_ICHOR_HIDDEN_ITEM_DEEP_BIG_PEARL")
    g.person("HESYCHIOS", "ACOLYTE_M", 21, 7, "Hesychios", facing="LEFT", sight=3)
    for key, x, y in (("crystal_l", 4, 14), ("crystal_tall", 10, 22), ("crystal_s", 6, 20), ("ice_rock", 22, 24),
                      ("crystal_s", 31, 12), ("ice_boulders", 27, 21), ("crystal_s", 12, 3), ("crystal_tall", 29, 4)):
        g.put(key, x, y)
    g.accents(salt=21, rate=4)
    g.save([wall()] * 4,
           dict(map_type="MAP_TYPE_UNDERGROUND", weather="WEATHER_NONE", show_map_name=False,
                allow_cycling=False, allow_escaping=True, requires_flash=True,
                music="MUS_VICTORY_ROAD", ichor_kind="dungeon"))
    must = [("shrine", (25, 4)), ("spell tag", (27, 6)), ("tarn shore", (17, 9))]
    seen = g.check((8, 5), must)
    assert (16, 1) not in seen and (15, 1) not in seen, "the meltwater ledge must need the Horn"
    s = """// The Icefall's deep (design/maps/Ascent_IcefallDeep.md): the coldest dark under the
// ice caves, lit only by Hecate's Torch; a black tarn (Poseidon's Conch).
// Generated by tools/ichor/maps/ascent_glacier.py: edit the builder, not this file.

mapscripts Ascent_IcefallDeep_MapScripts {}
"""
    s += trainer_script(P, "Hesychios", "DEEP_HESYCHIOS",
                        "Shh. I came down here for the quiet.\\pYou brought a fire and a fight. Fine. Only the fight.",
                        "…That was loud.",
                        "The water's the Styx's, they say. A trickle of it, come up under the mountain.\\p"
                        "The gods swore by it. Don't swear by anything down here.")
    s += sign_script(P, "Styx",
                     "A drowned shrine to Styx, the river the gods swore their oaths on.\\p"
                     "Words half under the ice:\\p"
                     "“Whoever breaks an oath sworn on my water lies a year without breath,\\p"
                     "and nine more without a seat at the feast.”")
    s += sign_script(P, "Meltfall",
                     "Meltwater pours down the ice here, loud in the dark: a spring from under the cone\\p"
                     "that the cold never stopped. Something glints at the top.\\p"
                     "A river god's horn could climb water like this.")
    write_scripts("Ascent_IcefallDeep", s)
    return g, seen, [("ladder", 8, 6), ("tarn", 17, 14), ("shrine", 24, 6), ("shore", 29, 15)]


