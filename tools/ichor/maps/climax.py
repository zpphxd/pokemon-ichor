def build_loom(render):
    m = SceneMap("TheLoom", "loom", loom_tiles, "loom_before")
    P = "TheLoom_EventScript_"
    m.header = {"ichor_kind": "interior", "allow_escaping": False, "allow_cycling": False}
    # the night's people; the cut hides them all (FLAG_ICHOR_CUT_THE_CHAINS)
    m.obj("ICHOR_PHAEDON", 29, 12, P + "Phaedon", "MOVEMENT_TYPE_FACE_LEFT", "FLAG_ICHOR_CUT_THE_CHAINS",
          local_id="LOCALID_LOOM_PHAEDON")
    m.obj("ICHOR_HYPERION", 22, 11, P + "Hyperion", "MOVEMENT_TYPE_FACE_UP", "FLAG_ICHOR_CUT_THE_CHAINS",
          local_id="LOCALID_LOOM_HYPERION")
    for name, sp, (x, y) in (("SPINNER", "NEMIRA", (6, 9)), ("MEASURER", "LOTIRA", (16, 9)),
                             ("CUTTER", "THANIRA", (27, 9))):
        m.obj(f"SPECIES({sp})", x, y, P + "Fate", "MOVEMENT_TYPE_WALK_IN_PLACE_DOWN",
              "FLAG_ICHOR_CUT_THE_CHAINS", local_id=f"LOCALID_LOOM_{name}")
    # the Lord of Time and the Harpe appear only in the scene (addobject)
    m.obj("SPECIES(KRONOLITH)", 16, 10, "0", "MOVEMENT_TYPE_FACE_DOWN", "FLAG_ICHOR_HIDE_FROZEN_ONLY",
          local_id="LOCALID_LOOM_LORD")["_floats"] = True
    m.obj("ICHOR_HARPE", 30, 12, "0", "MOVEMENT_TYPE_FACE_DOWN", "FLAG_ICHOR_HIDE_FROZEN_ONLY",
          local_id="LOCALID_LOOM_HARPE")
    # the way up (the Omphalos stair) and, after the cut, the Stair of Hours' foot
    m.trigger(33, 12, P + "LeaveUp")
    # warp 0: where the Omphalos stair comes down (Delphoi_OmphalosStair's warp 2 and 3)
    m.warp(33, 12, "MAP_DELPHOI_OMPHALOS_STAIR", 2)
    m.trigger(1, 11, P + "StairFoot")
    m.trigger(2, 11, P + "StairFoot")
    m.forced_open |= {(1, 11), (2, 11), (2, 12)}
    # the warp, the last row, the chasm, the case
    for x in (7, 17, 26):
        m.sign(x, 8, P + "Thread")
    m.sign(16, 8, P + "LastRow")
    m.sign(12, 10, P + "Chasm")
    m.sign(23, 10, P + "Chasm")
    m.sign(1, 10, P + "PaleStair")
    must = [(16, 9, "the Measurer's spur"), (6, 9, "the Spinner's spur"), (27, 9, "the Cutter's spur")]
    m.build("the_loom", starts=[(32, 12)], must_reach=must,
            views=[(26, 9), (16, 7), (7, 7)], render=render)


