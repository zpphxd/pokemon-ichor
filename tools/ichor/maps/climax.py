def build_stair(render):
    import loom_art as A
    m = SceneMap("StairOfHours", "stair_of_hours", stair_of_hours_tiles, "stair")
    P = "StairOfHours_EventScript_"
    m.header = {"ichor_kind": "interior", "allow_escaping": False, "allow_cycling": False}
    L = {k: A.landing_rect(k) for k in range(1, 13)}
    D = {k: A.dial_cell(k) for k in range(1, 13)}

    def spot(k, dx, dy):
        x0, x1, t, face = L[k]
        return (x0 + dx if dx >= 0 else x1 + 1 + dx), t + dy

    # frozen Titanborn following their master up (landings 1, 2, 3 and 5)
    grunts = [(2, 1, 3, "UP", "Titanborn"), (2, -3, 3, "UP", "TitanbornShut"), (3, 2, 1, "LEFT", "Titanborn"),
              (3, -2, 3, "UP", "Titanborn"), (5, 2, 3, "RIGHT", "Petros"), (5, 3, 3, "LEFT", "Amathos")]
    for i, (k, dx, dy, face, scr) in enumerate(grunts):
        x, y = spot(k, dx, dy)
        lid = {"Petros": "LOCALID_STAIR_PETROS", "Amathos": "LOCALID_STAIR_AMATHOS"}.get(scr)
        m.obj("ICHOR_TITAN_GRUNT", x, y, P + scr, f"MOVEMENT_TYPE_ICHOR_FROZEN_STEP_{face}",
              local_id=lid)
    # what the climbing Titanborn dropped (P6)
    for k, item, flag in ((3, "ITEM_FULL_RESTORE", "FLAG_ICHOR_ITEM_STAIR_FULL_RESTORE_1"),
                          (7, "ITEM_MAX_REVIVE", "FLAG_ICHOR_ITEM_STAIR_MAX_REVIVE"),
                          (10, "ITEM_FULL_RESTORE", "FLAG_ICHOR_ITEM_STAIR_FULL_RESTORE_2")):
        x, y = spot(k, 1 if k % 2 else -2, 3)
        m.item_ball(x, y, item, flag)
    # the Fates' sparks that heal, by the dials of landings 4, 8 and 11 (and 12, after)
    for k in (4, 8, 11):
        dx, dy = D[k]
        m.obj("ICHOR_SPARK", dx + 2, dy, P + "Spark", local_id=f"LOCALID_STAIR_SPARK_{k}")
    m.obj("ICHOR_SPARK", 8, 12, P + "Spark", flag="FLAG_ICHOR_HIDE_STAIR_SPARK", local_id="LOCALID_STAIR_SPARK_12")
    # Kleon on the climb (landing 2) and at the top
    x, y = spot(2, 6, 1)
    m.obj("ICHOR_KLEON_FREE", x, y, P + "KleonClimb", "MOVEMENT_TYPE_FACE_DOWN", "FLAG_ICHOR_HIDE_STAIR_KLEON",
          local_id="LOCALID_STAIR_KLEON_CLIMB")
    m.obj("ICHOR_KLEON_FREE", 14, 15, P + "KleonTop", "MOVEMENT_TYPE_FACE_UP", "FLAG_ICHOR_HIDE_STAIR_KLEON_TOP",
          local_id="LOCALID_STAIR_KLEON")
    # the twelfth landing
    m.obj("ICHOR_PHAEDON", 12, 14, P + "Phaedon", "MOVEMENT_TYPE_FACE_DOWN", "FLAG_ICHOR_HIDE_STAIR_RIVALS",
          local_id="LOCALID_STAIR_PHAEDON")
    m.obj("ICHOR_HYPERION", 13, 13, P + "Hyperion", "MOVEMENT_TYPE_FACE_DOWN", "FLAG_ICHOR_HIDE_STAIR_HYPERION",
          local_id="LOCALID_STAIR_HYPERION")
    m.obj("SPECIES(KRONOLITH)", 13, 9, P + "Lord", "MOVEMENT_TYPE_FACE_DOWN", "FLAG_ICHOR_HIDE_STAIR_LORD",
          local_id="LOCALID_STAIR_LORD")["_floats"] = True
    for name, sp, (x, y) in (("SPINNER", "NEMIRA", (6, 13)), ("MEASURER", "LOTIRA", (16, 14)),
                             ("CUTTER", "THANIRA", (15, 12))):
        m.obj(f"SPECIES({sp})", x, y, P + "Fate", "MOVEMENT_TYPE_FACE_DOWN", "FLAG_ICHOR_HIDE_STAIR_FATES",
              local_id=f"LOCALID_STAIR_{name}")
    m.obj("SPECIES(KAIRAZOR)", 19, 13, "0", "MOVEMENT_TYPE_FACE_LEFT", "FLAG_ICHOR_HIDE_STAIR_FATES",
          local_id="LOCALID_STAIR_MOMENT")["_floats"] = True
    m.obj("ICHOR_HARPE", 14, 10, "0", "MOVEMENT_TYPE_FACE_DOWN", "FLAG_ICHOR_HIDE_STAIR_FATES",
          local_id="LOCALID_STAIR_HARPE")["_floats"] = True
    # triggers: the foot (back down), Kleon's line on landing 2, the twelfth landing,
    # the Lord of Time's shadow, the painted line where the Moment runs
    for x in (5, 6, 7):
        m.trigger(x, 109, P + "Down")
    x0, x1, t, face = L[2]
    for x in (13, 14, 15):
        m.trigger(x, t + 3, P + "KleonLine", var="VAR_ICHOR_ACT3", value=16)
    for x in (11, 12, 13):
        m.trigger(x, 15, P + "TwelfthLanding", var="VAR_ICHOR_ACT3", value=16)
    for x in (12, 13, 14):
        m.trigger(x, 12, P + "Shadow", var="VAR_ICHOR_ACT3", value=17)
    # the dials (read from below), and the held-breath steps of the gated flights
    for k in range(1, 13):
        dx, dy = D[k]
        m.sign(dx, dy + 1, P + f"Dial{k}")
        m.sign(dx + 1, dy + 1, P + f"Dial{k}")
    for k in (5, 9):
        row, x0 = A.flight_cells(k)[0]
        m.sign(x0 + 1, row, P + "HeldStep")
    starts = [(6, 108)]
    must = [(12, 13, "the twelfth landing"), (12, 12, "the Lord of Time's shadow")]
    views = [(6, 104), (17, 93), (6, 77), (17, 61), (6, 45), (12, 14)]
    m.build("stair_of_hours", starts=starts, must_reach=must, views=views, render=render)


def main():
    render = "--no-render" not in sys.argv
    write_tiles_pory()
    build_loom(render)
    build_stair(render)


if __name__ == "__main__":
    main()
