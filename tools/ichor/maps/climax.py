#!/usr/bin/env python3
"""MAP_THE_LOOM and MAP_STAIR_OF_HOURS, the climax's set pieces (design/phase4/SCRIPT.md
III-9 to III-11; briefs in design/maps/TheLoom.md and StairOfHours.md).

Both layouts are the painted scenes of tools/ichor/art/loom_build.py, cell for cell
(tools/ichor/maps/loom_tiles.py, stair_of_hours_tiles.py): the Loom as it is on the
night of the Omphalos, the Stair with every flight solid. The scripts swap in the
other states from data/scripts/ichor_climax_tiles.pory, which this writes:

  TheLoom_Tiles_After          the cut: broken chains, the torn roof, the Stair's foot
  StairOfHours_Tiles_Ghost<k>  flight k (1, 5, 9) unformed until its Fate is roused
  StairOfHours_Tiles_Fall<k>   flight k falls away, row by row (the crumble, III-11C)
  StairOfHours_Tiles_Fallen    every flight gone at once (a load after the crumble)

It then places the events, checks the maps (kythera_maps.Map) and renders them into
design/phase4/img/maps/.

  /usr/bin/python3 tools/ichor/maps/climax.py [--no-render]
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "art"))
import kythera_maps as KM  # noqa: E402
import loom_tiles  # noqa: E402
import stair_of_hours_tiles  # noqa: E402

ROOT = KM.ROOT
TILES_PORY = ROOT / "data/scripts/ichor_climax_tiles.pory"


class SceneMap(KM.Map):
    """A kythera_maps.Map on the oikos primary whose cells come from a painted scene."""

    def __init__(self, name, ts_dir, catalog, scene):
        sc = catalog.SCENES[scene]
        self.name, self.ts, self.w, self.h, self.primary = name, ts_dir, sc["w"], sc["h"], "oikos"
        self.cat = {"symbol": catalog.SYMBOL, "structures": {}, "fronts": {}}
        self.mid = np.array(sc["ids"], np.uint16)
        self.solid = np.array([[c == "X" for c in row] for row in sc["walk"]], bool)
        self.pattr = KM._attrs("data/tilesets/primary/oikos/porytiles_bin/metatile_attributes.bin")
        self.sattr = KM._attrs(f"data/tilesets/secondary/{ts_dir}/porytiles_bin/metatile_attributes.bin")
        self.objects, self.warps, self.coords, self.bgs, self.connections = [], [], [], [], []
        self.seams = []
        self.border = [int(sc["ids"][0][0])] * 4
        self.header = {}
        self.forced_open = set()


def delta(catalog, a, b, cells=None):
    """[(x, y, id, solid)] where scene b differs from scene a (or at `cells`)."""
    A, B = catalog.SCENES[a], catalog.SCENES[b]
    out = []
    for y in range(A["h"]):
        for x in range(A["w"]):
            if cells is not None and (x, y) not in cells:
                continue
            if cells is None and A["ids"][y][x] == B["ids"][y][x] and A["walk"][y][x] == B["walk"][y][x]:
                continue
            out.append((x, y, B["ids"][y][x], B["walk"][y][x] == "X"))
    return out


def tiles_script(name, cells, draw=True):
    lines = [f"script {name} {{"]
    for x, y, mid, solid in cells:
        lines.append(f"    setmetatile({x}, {y}, 0x{mid:03X}, {'TRUE' if solid else 'FALSE'})")
    if draw:
        lines.append("    special(DrawWholeMapView)")
    lines.append("    return")
    lines.append("}")
    return "\n".join(lines)


def write_tiles_pory():
    import loom_art as A
    out = ["// Generated by tools/ichor/maps/climax.py from the painted scenes; do not edit.",
           "// Each script swaps one state of a climax map in with setmetatile.", ""]
    after = delta(loom_tiles, "loom_before", "loom_after")
    out.append(tiles_script("TheLoom_Tiles_After", after, draw=False))
    # the scene's steps: each chain parts, then the roof tears and the Stair's foot stands
    for name, (xa, xb) in (("Spinner", (3, 10)), ("Measurer", (13, 20)), ("Cutter", (23, 31)),
                           ("Hole", (0, 2))):
        out.append(tiles_script(f"TheLoom_Tiles_{name}", [c for c in after if xa <= c[0] <= xb]))
    for k in (1, 5, 9):
        cells = {(x0 + i, row) for row, x0 in A.flight_cells(k) for i in range(3)}
        out.append(tiles_script(f"StairOfHours_Tiles_Ghost{k}", delta(stair_of_hours_tiles, "stair", "stair_ghost",
                                                                      cells), draw=False))
    allcells = set()
    for k in range(2, 13):
        rows = A.flight_cells(k)
        for row, x0 in rows:
            allcells |= {(x0 + i, row) for i in range(3)}
        # top row first: the stair falls away behind the two going down
        body = [f"script StairOfHours_Tiles_Fall{k} {{"]
        for row, x0 in reversed(rows):
            for x, y, mid, solid in delta(stair_of_hours_tiles, "stair", "stair_fallen",
                                          {(x0 + i, row) for i in range(3)}):
                body.append(f"    setmetatile({x}, {y}, 0x{mid:03X}, TRUE)")
            body.append("    special(DrawWholeMapView)")
            body.append("    playse(SE_M_ROCK_THROW)")
            body.append("    delay(6)")
        body.append("    return")
        body.append("}")
        out.append("\n".join(body))
    out.append(tiles_script("StairOfHours_Tiles_Fallen",
                            [(x, y, m, True) for x, y, m, s in delta(stair_of_hours_tiles, "stair", "stair_fallen",
                                                                       allcells)], draw=False))
    TILES_PORY.write_text("\n\n".join(out) + "\n")


