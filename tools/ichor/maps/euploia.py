def variant_block(cat):
    base = cat["scenes"]["below"]["ids"]
    walk = cat["scenes"]["below"]["walk"]
    lines = [GEN_START,
             "// Each sets the cells one state of below deck changes; ON_LOAD runs them",
             "// before the map draws. From a script, follow with special(DrawWholeMapView).",
             "// Rebuild with tools/ichor/maps/euploia.py after the tileset changes."]

    def script(name, cells):
        lines.append(f"script {name} {{")
        for x, y, i in cells:
            solid = "TRUE" if walk[y][x] in "Xc~" else "FALSE"
            lines.append(f"    setmetatile({x}, {y}, 0x{i:03X}, {solid})")
        lines.append("    return")
        lines.append("}")

    cold = [tuple(c) for c in cat["variants"]["hearth_cold"]]
    script("EuploiaBelow_EventScript_HearthCold", cold)
    script("EuploiaBelow_EventScript_HearthLit", [(x, y, base[y][x]) for x, y, _ in cold])
    for name, _, _ in EB.KEEPSAKES:
        cells = [tuple(c) for c in cat["variants"][f"keepsake_{name}"]]
        script(f"EuploiaBelow_EventScript_Keepsake{name.capitalize()}", cells)
    lines.append(GEN_END)
    return "\n".join(lines)


def write_variant_scripts(cat):
    text = BELOW_PORY.read_text()
    block = variant_block(cat)
    if GEN_START in text:
        a, b = text.index(GEN_START), text.index(GEN_END) + len(GEN_END)
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    BELOW_PORY.write_text(text)


