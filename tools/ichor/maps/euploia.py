def load_catalog():
    if not CAT.exists():
        sys.exit(f"{CAT} is missing; run tools/ichor/art/euploia_build.py first")
    return json.loads(CAT.read_text())


def encode(ids, walk):
    """Blockdata: metatile id, collision and elevation from the scene's walk codes."""
    h, w = len(ids), len(ids[0])
    out = np.zeros((h, w), np.uint16)
    for y in range(h):
        for x in range(w):
            code = walk[y][x]
            solid = code in "X~c"
            elev = 1 if code == "~" else 3
            out[y, x] = ids[y][x] | (SOLID if solid else 0) | (elev << 12)
    return out


def layout_dir(m):
    return ROOT / "data/layouts" / m["name"]


def write_layouts(cat):
    for m, key, border in ((DECK, "deck", SEA | (1 << 12)), (BELOW, "below", cat["void"] | SOLID)):
        sc = cat["scenes"][key]
        d = layout_dir(m)
        d.mkdir(parents=True, exist_ok=True)
        encode(sc["ids"], sc["walk"]).astype("<u2").tofile(d / "map.bin")
        np.full(4, border, np.uint16).astype("<u2").tofile(d / "border.bin")
    data = json.loads(LAYOUTS.read_text())
    for lay in data["layouts"]:
        for m in (DECK, BELOW):
            if lay.get("name") == m["name"] + "_Layout":
                lay["width"], lay["height"] = m["w"], m["h"]
                lay["primary_tileset"], lay["secondary_tileset"] = "gTileset_Aethos", "gTileset_Euploia"
    LAYOUTS.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


