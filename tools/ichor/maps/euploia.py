"""Build the Euploia refitted: her deck and below deck, their events, the
trophy shelf's and the hearth's setmetatile scripts, and their checks.

Writes:
  data/layouts/EuploiaDeck/map.bin, border.bin     (24x12, aethos + euploia)
  data/layouts/EuploiaBelow/map.bin, border.bin    (20x10, aethos + euploia)
  both layouts' size in data/layouts/layouts.json
  data/maps/EuploiaDeck/map.json, data/maps/EuploiaBelow/map.json: the header
    and every event, placed from the art's own constants (euploia_deck.py,
    euploia_below.py), so the people stand where the furniture is
  the generated block of data/maps/EuploiaBelow/scripts.pory: one small
    script per setmetatile variant (the hearth cold and lit, each keepsake)

Both maps are the scenes cell for cell (build/euploia/catalog.json; see
design/postgame/TILES_euploia.md). Then it checks the maps against their
blockdata: the warps sit on the hatch and the ladder, people stand where they
can be talked to and wall nothing off, every bg event can be read, and open
sea is solid.

Make the catalog first:
  /usr/bin/python3 tools/ichor/art/euploia_build.py

Usage: /usr/bin/python3 tools/ichor/maps/euploia.py [--render DIR] [--no-check]
  --render writes euploia_deck.png and euploia_below.png (2x), collision
  overlays, the shelf full, the hearth cold, and GBA-screen crops into DIR.
"""
