def render_blocks(blocks, width, out, scale=2):
    tmp = out.with_suffix(".bin")
    blocks.astype("<u2").tofile(tmp)
    subprocess.run([sys.executable, str(ROOT / "tools/ichor/render_map.py"), "--blockdata", str(tmp),
                    "--width", str(width), "--primary", "aethos", "--secondary", "euploia",
                    "--scale", str(scale), "-o", str(out)], check=True, stdout=subprocess.DEVNULL)
    tmp.unlink()


def with_variant(cat, blocks, *names):
    b = blocks.copy()
    for n in names:
        for x, y, i in cat["variants"][n]:
            b[y, x] = (int(b[y, x]) & 0xFC00) | i
    return b


def padded(blocks, border, margin):
    h, w = blocks.shape
    big = np.empty((h + 2 * margin, w + 2 * margin), np.uint16)
    big[:] = border
    big[margin:margin + h, margin:margin + w] = blocks
    return big


def overlay(png, blocks, json_path, out):
    from PIL import Image, ImageDraw
    im = Image.open(png).convert("RGBA")
    lay = Image.new("RGBA", im.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(lay)
    c = 32
    for y, row in enumerate(blocks):
        for x, b in enumerate(row):
            if b >> 10 & 3:
                d.rectangle([x * c, y * c, x * c + c - 1, y * c + c - 1], fill=(255, 0, 0, 60))
    ev = json.loads(json_path.read_text())
    for o in ev["object_events"]:
        d.ellipse([o["x"] * c + 4, o["y"] * c + 4, o["x"] * c + c - 5, o["y"] * c + c - 5],
                  outline=(255, 255, 0, 255), width=2)
    for w in ev["warp_events"]:
        d.rectangle([w["x"] * c + 2, w["y"] * c + 2, w["x"] * c + c - 3, w["y"] * c + c - 3],
                    outline=(0, 255, 255, 255), width=2)
    for b in ev["bg_events"]:
        d.line([b["x"] * c + 3, b["y"] * c + 3, b["x"] * c + c - 4, b["y"] * c + c - 4], fill=(255, 255, 255, 255), width=2)
        d.line([b["x"] * c + c - 4, b["y"] * c + 3, b["x"] * c + 3, b["y"] * c + c - 4], fill=(255, 255, 255, 255), width=2)
    Image.alpha_composite(im, lay).save(out)


def render(cat, out_dir):
    from PIL import Image
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    deck = np.fromfile(layout_dir(DECK) / "map.bin", "<u2").reshape(DECK["h"], DECK["w"])
    below = np.fromfile(layout_dir(BELOW) / "map.bin", "<u2").reshape(BELOW["h"], BELOW["w"])
    render_blocks(deck, DECK["w"], out_dir / "euploia_deck.png")
    render_blocks(below, BELOW["w"], out_dir / "euploia_below.png")
    full = with_variant(cat, below, *[f"keepsake_{k}" for k, _, _ in EB.KEEPSAKES])
    render_blocks(full, BELOW["w"], out_dir / "euploia_below_shelf_full.png")
    render_blocks(with_variant(cat, below, "hearth_cold"), BELOW["w"], out_dir / "euploia_below_cold.png")
    overlay(out_dir / "euploia_deck.png", deck, ROOT / "data/maps/EuploiaDeck/map.json", out_dir / "euploia_deck_walk.png")
    overlay(out_dir / "euploia_below.png", below, ROOT / "data/maps/EuploiaBelow/map.json", out_dir / "euploia_below_walk.png")
    # GBA-screen crops (15x10) where the player stands
    crops = []
    margin = 8
    for blocks, border, w, spots in ((deck, SEA | (1 << 12), DECK["w"], ((5, 5), (11, 5), (18, 5))),
                                     (below, cat["void"], BELOW["w"], ((4, 4), (11, 5), (15, 5)))):
        big = padded(blocks, border, margin)
        render_blocks(big, big.shape[1], out_dir / "padded.png")
        im = Image.open(out_dir / "padded.png")
        c = 32
        for (px, py) in spots:
            x0, y0 = (px - 7 + margin) * c, (py - 4 + margin) * c
            crops.append(im.crop((x0, y0, x0 + 15 * c, y0 + 10 * c)))
        (out_dir / "padded.png").unlink()
    cols = 3
    sheet = Image.new("RGB", (cols * 15 * 32 + 16, -(-len(crops) // cols) * (10 * 32 + 8) - 8), (24, 24, 32))
    for i, crop in enumerate(crops):
        sheet.paste(crop, ((i % cols) * (15 * 32 + 8), (i // cols) * (10 * 32 + 8)))
    sheet.save(out_dir / "euploia_screens.png")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--render", metavar="DIR")
    ap.add_argument("--no-check", action="store_true")
    args = ap.parse_args()
    cat = load_catalog()
    write_layouts(cat)
    write_maps()
    write_variant_scripts(cat)
    if args.render:
        render(cat, args.render)
    if not args.no_check:
        errors = check()
        for e in errors:
            print("CHECK:", e)
        if errors:
            sys.exit(1)
        print("euploia: layouts, events and variant scripts written, checks pass")


if __name__ == "__main__":
    main()
