def behavior_names():
    import re
    txt = (ROOT / "include/constants/metatile_behaviors.h").read_text()
    out, v = {}, 0
    for name, val in re.findall(r"^\s*(MB_\w+)\s*(?:=\s*(\w+))?\s*,", txt, re.M):
        if val:
            v = int(val, 0)
        out[v] = name
        v += 1
    return out


MB = behavior_names()


def attrs():
    return (np.fromfile(ROOT / "data/tilesets/primary/aethos/porytiles_bin/metatile_attributes.bin", "<u2"),
            np.fromfile(ROOT / "data/tilesets/secondary/euploia/porytiles_bin/metatile_attributes.bin", "<u2"))


def behavior(mid, at):
    a = at[0][mid] if mid < 0x200 else at[1][mid - 0x200]
    return MB.get(int(a) & 0xFF, "?")


def walkable(blocks, x, y):
    h, w = blocks.shape
    return 0 <= x < w and 0 <= y < h and not (blocks[y, x] >> 10 & 3) and blocks[y, x] >> 12 != 1


def reachable(blocks, start, blocked=()):
    seen, q = {start}, deque([start])
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            p = (x + dx, y + dy)
            if p not in seen and p not in blocked and walkable(blocks, *p):
                seen.add(p)
                q.append(p)
    return seen


FACE_FROM = {N: [(0, 1)], S_: [(0, -1)], W_: [(1, 0)], ANY: [(0, 1), (0, -1), (1, 0), (-1, 0)],
             "BG_EVENT_PLAYER_FACING_EAST": [(-1, 0)]}


def check():
    errors = []
    at = attrs()
    for m, people, warps, bgs, start in ((DECK, DECK_PEOPLE, DECK_WARPS, DECK_BGS, (ED.HATCH[0] + 1, ED.HATCH[1])),
                                         (BELOW, BELOW_PEOPLE, BELOW_WARPS, BELOW_BGS, EB.LADDER)):
        name = m["name"]
        blocks = np.fromfile(layout_dir(m) / "map.bin", "<u2").reshape(m["h"], m["w"])
        reach = reachable(blocks, start)
        still = {xy for _, _, xy, _, _, _ in people if walkable(blocks, *xy)}
        reach_still = reachable(blocks, start, still - {start})
        for (x, y), _, _ in warps:
            b = behavior(int(blocks[y, x]) & 0x3FF, at)
            if b != "MB_LADDER":
                errors.append(f"{name}: warp at ({x},{y}) is on {b}, not a ladder")
            if (x, y) not in reach:
                errors.append(f"{name}: warp at ({x},{y}) is unreachable")
            fronts = [(x + dx, y + dy) for dx, dy in ((0, 1), (0, -1), (1, 0), (-1, 0))]
            if not any(p in reach_still for p in fronts):
                errors.append(f"{name}: the warp at ({x},{y}) is walled off by people")
        for lid, _, (x, y), _, _, _ in people:
            fronts = [(x + dx, y + dy) for dx, dy in ((0, 1), (0, -1), (1, 0), (-1, 0))]
            # across a counter: Kydon is talked to from two tiles south
            fronts += [(x, y + 2)] if behavior(int(blocks[min(y + 1, m["h"] - 1), x]) & 0x3FF, at) == "MB_COUNTER" else []
            if not any(p in reach_still for p in fronts):
                errors.append(f"{name}: {lid} at ({x},{y}) can't be talked to with everyone aboard")
        for (x, y), face, script in bgs:
            spots = [(x + dx, y + dy) for dx, dy in FACE_FROM[face]]
            if not any(p in reach and p not in still for p in spots):
                errors.append(f"{name}: bg event {script} at ({x},{y}) can't be read")
        for y in range(m["h"]):
            for x in range(m["w"]):
                if int(blocks[y, x]) & 0x3FF == SEA and not blocks[y, x] >> 10 & 3:
                    errors.append(f"{name}: open sea at ({x},{y}) is passable")
    return errors


