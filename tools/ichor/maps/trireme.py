def behavior_names():
    txt = (ROOT / "include/constants/metatile_behaviors.h").read_text()
    out, v = {}, 0
    for name, val in re.findall(r"^\s*(MB_\w+)\s*(?:=\s*(\w+))?\s*,", txt, re.M):
        if val:
            v = int(val, 0)
        out[v] = name
        v += 1
    return out


MB = behavior_names()
AETHOS_ATTR = np.fromfile(ROOT / "data/tilesets/primary/aethos/porytiles_bin/metatile_attributes.bin", "<u2")
TRIREME_ATTR = np.fromfile(ROOT / "data/tilesets/secondary/trireme/porytiles_bin/metatile_attributes.bin", "<u2")


def behavior(mid):
    a = AETHOS_ATTR[mid] if mid < 0x200 else TRIREME_ATTR[mid - 0x200]
    return MB.get(int(a) & 0xFF, "?")


def walkable(blocks, x, y):
    h, w = blocks.shape
    return 0 <= x < w and 0 <= y < h and not (blocks[y, x] >> 10 & 3) and blocks[y, x] >> 12 != 1


def reachable(blocks, start, blocked=()):
    seen, q = {start}, deque([start])
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            p = (x + dx, y + dy)
            if p not in seen and p not in blocked and walkable(blocks, *p):
                seen.add(p)
                q.append(p)
    return seen


# Objects that may hang over the sea or stand off the deck: the scene's birds,
# the nest, the dark trireme, and people placed somewhere only a script moves them
OFF_DECK_GFX = ("HARPECK", "GALENYON", "HALCYLING", "NEST", "DARK_TRIREME")


def check():
    errors = []
    for name, path, width in (("deck", DECK_DIR, 24), ("hold", HOLD_DIR, 18)):
        blocks = np.fromfile(path / "map.bin", "<u2").reshape(-1, width)
        ev = json.loads((DECK_JSON if name == "deck" else HOLD_JSON).read_text())
        warps = [(w["x"], w["y"]) for w in ev["warp_events"]]
        start = BOARDING if name == "deck" else LADDER
        objects = {(o["x"], o["y"]): o for o in ev["object_events"]}
        still = {p for p, o in objects.items()
                 if not any(g in o["graphics_id"] for g in OFF_DECK_GFX) and o.get("flag") not in
                 ("FLAG_ICHOR_HIDE_HALCYON_NEST", "FLAG_ICHOR_HIDE_DECK_HARPECK")}
        reach = reachable(blocks, start)
        for i, (x, y) in enumerate(warps):
            b = behavior(int(blocks[y, x]) & 0x3FF)
            if name == "deck" and i == 0:
                if (x, y) != BOARDING or not walkable(blocks, x, y):
                    errors.append(f"deck: warp 0 should be the walkable boarding tile {BOARDING}")
                continue
            if b != "MB_LADDER":
                errors.append(f"{name}: warp {i} at ({x},{y}) is on {b}, not the ladder")
            if (x, y) not in reach:
                errors.append(f"{name}: warp {i} at ({x},{y}) is unreachable")
        for o in ev["object_events"]:
            x, y = o["x"], o["y"]
            if any(g in o["graphics_id"] for g in OFF_DECK_GFX):
                continue
            if o["graphics_id"] == "OBJ_EVENT_GFX_ITEM_BALL" and name == "hold":
                fronts = [(x, y - 1), (x, y + 1), (x - 1, y), (x + 1, y)]
                if not any(p in reach for p in fronts):
                    errors.append(f"hold: the item at ({x},{y}) can't be reached")
                continue
            if name == "hold" and o["movement_type"].startswith("MOVEMENT_TYPE_FACE"):
                # rowers sit on the benches: they must be talkable from the gangway
                fronts = [(x, y - 1), (x, y + 1), (x - 1, y), (x + 1, y)]
                if not any(p in reach for p in fronts):
                    errors.append(f"hold: {o.get('local_id', o['graphics_id'])} at ({x},{y}) can't be talked to")
                continue
            if not walkable(blocks, x, y):
                errors.append(f"{name}: object {o.get('local_id', o['graphics_id'])} at ({x},{y}) "
                              f"stands on a solid cell")
        for b in ev["bg_events"]:
            x, y = b["x"], b["y"]
            fronts = [(x, y + 1), (x, y - 1), (x - 1, y), (x + 1, y)]
            if not any(p in reach and p not in still for p in fronts):
                errors.append(f"{name}: bg event at ({x},{y}) can't be read from the deck")
        # nobody stands where they wall off a thing to read, a person or the ladder
        blocked = still - {start}
        reach_still = reachable(blocks, start, blocked)
        for (x, y), o in objects.items():
            if (x, y) not in still:
                continue
            fronts = [(x, y - 1), (x, y + 1), (x - 1, y), (x + 1, y)]
            if not any(p in reach_still for p in fronts):
                errors.append(f"{name}: {o.get('local_id', o['graphics_id'])} at ({x},{y}) is walled "
                              f"off by the others")
        for (x, y) in warps:
            if name == "deck" and (x, y) == BOARDING:
                continue
            fronts = [(x, y - 1), (x, y + 1), (x - 1, y), (x + 1, y)]
            if not any(p in reach_still for p in fronts):
                errors.append(f"{name}: the warp at ({x},{y}) is walled off by people")
        if name == "deck":
            # every gap in the rail is fishable from the deck
            gaps = [(x, y) for y in range(blocks.shape[0]) for x in range(width)
                    if behavior(int(blocks[y, x]) & 0x3FF) == "MB_OCEAN_WATER" and int(blocks[y, x]) & 0x3FF != SEA]
            if len(gaps) < 3:
                errors.append(f"deck: only {len(gaps)} fishing gaps")
            for (x, y) in gaps:
                if blocks[y, x] >> 10 & 3 or blocks[y, x] >> 12 != 1:
                    errors.append(f"deck: gap ({x},{y}) must be walkable collision at water elevation")
                if not any(p in reach for p in ((x, y + 1), (x, y - 1))):
                    errors.append(f"deck: gap ({x},{y}) has no deck to fish from")
            # open sea is solid, so a surfer can't leave the ship
            for y in range(blocks.shape[0]):
                for x in range(width):
                    if int(blocks[y, x]) & 0x3FF == SEA and not blocks[y, x] >> 10 & 3:
                        errors.append(f"deck: open sea at ({x},{y}) is passable")
            for who, cells in SCRIPTED_PATHS.items():
                for (x, y) in cells:
                    if not walkable(blocks, x, y):
                        errors.append(f"deck: {who} crosses solid ({x},{y})")
            # Phormion's sight covers the deck's height at his column, so the way aft
            # passes him (MAP_DESIGN §1: the first trainer, in plain view)
            for o in ev["object_events"]:
                if o.get("trainer_type") == "TRAINER_TYPE_NORMAL" and "PHORMION" in o["script"].upper():
                    x, y, r = o["x"], o["y"], int(o["trainer_sight_or_berry_tree_id"])
                    col = [(x, yy) for yy in range(y - r, y) if walkable(blocks, x, yy)]
                    open_col = [(x, yy) for yy in range(4, 10) if walkable(blocks, x, yy) and yy != y]
                    if set(open_col) - set(col):
                        errors.append(f"deck: Phormion's sight at ({x},{y}) misses {sorted(set(open_col) - set(col))}")
    return errors


