# The variant scripts, generated into the deck's scripts.pory
# ---------------------------------------------------------------------------

VARIANT_SCRIPTS = [
    # name, variant whose cells to set, or None for the plain deck over those variants' cells
    ("TriremeDeck_EventScript_SailSag", "sail_sag", None),
    ("TriremeDeck_EventScript_SailFill", "sail_fill", None),
    ("TriremeDeck_EventScript_SailFull", None, ("sail_sag", "sail_fill")),
    ("TriremeDeck_EventScript_OarsOut", "oars_out", None),
    ("TriremeDeck_EventScript_OarsIn", None, ("oars_out",)),
    ("TriremeDeck_EventScript_KlepsydraUp", "klepsydra_up", None),
    ("TriremeDeck_EventScript_KlepsydraDown", None, ("klepsydra_up",)),
    ("TriremeDeck_EventScript_CoastOn", "coast", None),
    ("TriremeDeck_EventScript_CoastOff", None, ("coast",)),
]


def variant_block(cat):
    base = cat["scenes"]["deck"]["ids"]
    walk = cat["scenes"]["deck"]["walk"]
    lines = [GEN_START,
             "// Each sets the cells one state of the deck changes; follow with",
             "// special(DrawWholeMapView) to show it at once. Rebuild with",
             "// tools/ichor/maps/trireme.py after the tileset changes."]
    for name, var, undo in VARIANT_SCRIPTS:
        if var:
            cells = [(x, y, i) for x, y, i in cat["variants"][var]]
        else:
            seen = sorted({(x, y) for v in undo for x, y, _ in cat["variants"][v]}, key=lambda p: (p[1], p[0]))
            cells = [(x, y, base[y][x]) for x, y in seen]
        lines.append(f"script {name} {{")
        for x, y, i in cells:
            solid = "TRUE" if walk[y][x] in "X~" else "FALSE"
            lines.append(f"    setmetatile({x}, {y}, 0x{i:03X}, {solid})")
        lines.append("}")
    lines.append(GEN_END)
    return "\n".join(lines)


def write_variant_scripts(cat):
    text = DECK_PORY.read_text()
    block = variant_block(cat)
    if GEN_START in text:
        a, b = text.index(GEN_START), text.index(GEN_END) + len(GEN_END)
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    DECK_PORY.write_text(text)


