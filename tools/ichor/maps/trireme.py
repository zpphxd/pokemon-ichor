def render_blocks(blocks, width, out, scale=2, secondary="trireme"):
    tmp = out.with_suffix(".bin")
    blocks.astype("<u2").tofile(tmp)
    subprocess.run([sys.executable, str(ROOT / "tools/ichor/render_map.py"), "--blockdata", str(tmp),
                    "--width", str(width), "--primary", "aethos", "--secondary", secondary,
                    "--scale", str(scale), "-o", str(out)], check=True, stdout=subprocess.DEVNULL)
    tmp.unlink()


def with_variant(cat, blocks, *names):
    b = blocks.copy()
    for n in names:
        for x, y, i in cat["variants"][n]:
            b[y, x] = (int(b[y, x]) & 0xFC00) | i
    return b


def padded(blocks, border, margin):
    h, w = blocks.shape
    big = np.empty((h + 2 * margin, w + 2 * margin), np.uint16)
    for y in range(big.shape[0]):
        for x in range(big.shape[1]):
            big[y, x] = border[(y % 2) * 2 + x % 2]
    big[margin:margin + h, margin:margin + w] = blocks
    return big


# Where the player stands for each screen-sized review crop
SCREENS = {
    "1_boarding": (13, 4), "2_mast": (10, 7), "3_bow": (4, 6), "4_bow_rail": (6, 8),
    "5_stern": (18, 6), "6_port_rail": (14, 9), "7_night_rail": (8, 4),
}


def render(cat, out_dir):
    from PIL import Image
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    deck = np.fromfile(DECK_DIR / "map.bin", "<u2").reshape(16, 24)
    hold = np.fromfile(HOLD_DIR / "map.bin", "<u2").reshape(9, 18)
    render_blocks(deck, 24, out_dir / "trireme_deck.png")
    render_blocks(hold, 18, out_dir / "trireme_hold.png")
    for tag, names in (("calm", ("sail_sag", "oars_out", "klepsydra_up")), ("cast_off", ("sail_fill", "oars_out")),
                       ("last_leg", ("coast",))):
        render_blocks(with_variant(cat, deck, *names), 24, out_dir / f"trireme_deck_{tag}.png")
    overlay(out_dir / "trireme_deck.png", deck, DECK_JSON, out_dir / "trireme_deck_walk.png")
    overlay(out_dir / "trireme_hold.png", hold, HOLD_JSON, out_dir / "trireme_hold_walk.png")
    margin = 8
    big = padded(deck, [SEA] * 4, margin)
    render_blocks(big, big.shape[1], out_dir / "padded.png")
    im = Image.open(out_dir / "padded.png")
    c = 32
    crops = []
    for name, (px, py) in SCREENS.items():
        x0, y0 = (px - 7 + margin) * c, (py - 4 + margin) * c
        crop = im.crop((x0, y0, x0 + 15 * c, y0 + 10 * c))
        crop.save(out_dir / f"screen_{name}.png")
        crops.append(crop)
    cols = 2
    sheet = Image.new("RGB", (cols * 15 * c + 8, -(-len(crops) // cols) * (10 * c + 8) - 8), (24, 24, 32))
    for i, crop in enumerate(crops):
        sheet.paste(crop, ((i % cols) * (15 * c + 8), (i // cols) * (10 * c + 8)))
    sheet.save(out_dir / "trireme_screens.png")
    (out_dir / "padded.png").unlink()


def overlay(png, blocks, json_path, out):
    from PIL import Image, ImageDraw
    im = Image.open(png).convert("RGBA")
    lay = Image.new("RGBA", im.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(lay)
    c = 32
    for y, row in enumerate(blocks):
        for x, b in enumerate(row):
            if b >> 10 & 3:
                d.rectangle([x * c, y * c, x * c + c - 1, y * c + c - 1], fill=(255, 0, 0, 60))
            elif b >> 12 == 1:
                d.rectangle([x * c, y * c, x * c + c - 1, y * c + c - 1], fill=(0, 200, 255, 90))
    ev = json.loads(json_path.read_text())
    for o in ev["object_events"]:
        d.ellipse([o["x"] * c + 4, o["y"] * c + 4, o["x"] * c + c - 5, o["y"] * c + c - 5],
                  outline=(255, 255, 0, 255), width=2)
    for w in ev["warp_events"]:
        d.rectangle([w["x"] * c + 2, w["y"] * c + 2, w["x"] * c + c - 3, w["y"] * c + c - 3],
                    outline=(0, 255, 255, 255), width=2)
    for t in ev["coord_events"]:
        d.rectangle([t["x"] * c + 10, t["y"] * c + 10, t["x"] * c + c - 11, t["y"] * c + c - 11],
                    fill=(255, 0, 255, 180))
    for b in ev["bg_events"]:
        d.line([b["x"] * c + 3, b["y"] * c + 3, b["x"] * c + c - 4, b["y"] * c + c - 4], fill=(255, 255, 255, 255), width=2)
        d.line([b["x"] * c + c - 4, b["y"] * c + 3, b["x"] * c + 3, b["y"] * c + c - 4], fill=(255, 255, 255, 255), width=2)
    Image.alpha_composite(im, lay).save(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--render", metavar="DIR")
    ap.add_argument("--no-check", action="store_true")
    args = ap.parse_args()
    cat = load_catalog()
    write_layouts(cat)
    write_variant_scripts(cat)
    if args.render:
        render(cat, args.render)
    if not args.no_check:
        errors = check()
        for e in errors:
            print("CHECK:", e)
        if errors:
            sys.exit(1)
        print("trireme: layouts and variant scripts written, checks pass")


if __name__ == "__main__":
    main()
