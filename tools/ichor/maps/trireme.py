#!/usr/bin/env python3
"""Build the Euploia: the deck and the hold, their variant scripts and checks.

Writes:
  data/layouts/TriremeEuploia_Deck/map.bin, border.bin   (24x16, aethos + trireme)
  data/layouts/TriremeEuploia_Hold/map.bin, border.bin   (18x9, aethos + trireme)
  the generated block of data/maps/TriremeEuploia_Deck/scripts.pory: one small
    script per setmetatile variant (the sail, the oars, the klepsydra, the coast)

Both maps are the trireme scenes cell for cell (build/trireme/catalog.json; see
design/phase2/TILES_trireme.md). Then it checks both map.json files against
their blockdata: warps sit on the hatch and the ladder, people stand on deck,
bg events are readable, the rail's gaps can be fished from the deck, Phormion's
sight spans the deck, the scenes' scripted paths are clear, and the hold's
people don't wall anything off.

Make the catalog first:
  /usr/bin/python3 tools/ichor/art/trireme_build.py

Usage: /usr/bin/python3 tools/ichor/maps/trireme.py [--render DIR] [--no-check]
  --render writes trireme_deck.png and trireme_hold.png (2x), the deck in each
  variant, collision overlays and GBA-screen crops along the voyage into DIR.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from collections import deque
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
CAT = ROOT / "build/trireme/catalog.json"
DECK_DIR = ROOT / "data/layouts/TriremeEuploia_Deck"
HOLD_DIR = ROOT / "data/layouts/TriremeEuploia_Hold"
DECK_JSON = ROOT / "data/maps/TriremeEuploia_Deck/map.json"
HOLD_JSON = ROOT / "data/maps/TriremeEuploia_Hold/map.json"
DECK_PORY = ROOT / "data/maps/TriremeEuploia_Deck/scripts.pory"
SEA = 0x170
SOLID = 1 << 10
GEN_START = "// <generated by tools/ichor/maps/trireme.py: the deck's setmetatile variants>"
GEN_END = "// </generated>"

# The deck's fixed places (the scripts and BUILD.md use these)
BOARDING = (13, 4)       # warp 0: where a quay's gangplank puts the player (the entry port)
HATCH = (14, 7)          # warp 1: down to the hold
LADDER = (11, 5)         # the hold's warp 0: up to the hatch
HELM = (19, 6)           # the player at the steering oar, facing the tiller knob at (20,6)

# Cells the scenes walk people across: they must stay open.
SCRIPTED_PATHS = {
    # Kleon from the rail at (7,4) along row 4, down column 13, onto the hatch
    "Kleon to the hatch": [(x, 4) for x in range(7, 14)] + [(13, y) for y in range(4, 8)] + [HATCH],
    # the player from the trigger line x = 8 (any row) to the bow at (3,6)
    "player to the bow": [(8, y) for y in range(4, 10)] + [(x, 6) for x in range(3, 9)],
    # Alethea from the mast (10,7) along row 7 to (3,7)
    "Alethea to the bow": [(x, 7) for x in range(3, 11)],
    # the night: the player from the bow to (8,4) beside Kleon at (7,4); the lurch
    # slides them a tile aft
    "night leg": [(x, 6) for x in range(3, 9)] + [(8, 5), (8, 4), (9, 4), (7, 4), (8, 4)],
    # beat 10C: from the boarding tile to (8,4)
    "last leg": [(x, 4) for x in range(8, 14)],
    # the helm: the player takes the oar at (19,6); Nausikles steps to (19,7)
    "helm": [(18, 6), (19, 5), (19, 6), (19, 7)],
}


def load_catalog():
    if not CAT.exists():
        sys.exit(f"{CAT} is missing; run tools/ichor/art/trireme_build.py first")
    return json.loads(CAT.read_text())


def encode(ids, walk):
    """Blockdata: metatile id, collision and elevation from the scene's walk codes."""
    h, w = len(ids), len(ids[0])
    out = np.zeros((h, w), np.uint16)
    for y in range(h):
        for x in range(w):
            code = walk[y][x]
            solid = code in "X~"
            elev = 1 if code in "~f" else 3
            out[y, x] = ids[y][x] | (SOLID if solid else 0) | (elev << 12)
    return out


def write_layouts(cat):
    d, hd = cat["scenes"]["deck"], cat["scenes"]["hold"]
    DECK_DIR.mkdir(parents=True, exist_ok=True)
    HOLD_DIR.mkdir(parents=True, exist_ok=True)
    encode(d["ids"], d["walk"]).astype("<u2").tofile(DECK_DIR / "map.bin")
    np.full(4, SEA | (1 << 12), np.uint16).astype("<u2").tofile(DECK_DIR / "border.bin")
    encode(hd["ids"], hd["walk"]).astype("<u2").tofile(HOLD_DIR / "map.bin")
    np.full(4, cat["void"], np.uint16).astype("<u2").tofile(HOLD_DIR / "border.bin")


