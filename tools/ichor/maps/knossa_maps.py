"""Shared builder for Act III's Knossa maps above ground (design/phase4/SCRIPT.md
beats III-3A to III-4; design/maps/Knossa*.md hold each map's brief).

It is kythera_maps.Map reading the Knossa catalogs (knossa_tiles.py, generated by
world-act3's tools/ichor/art/knossa_build.py; design/phase4/TILES_amnisos.md,
TILES_bull_road.md, TILES_palace_minos.md, TILES_palace_rooms.md), plus
ensure_map(), which registers a map the first time its builder runs (layout,
map.json, scripts.pory, the Knossa map group, data/ichor_maps.inc, .gitignore).

    from knossa_maps import Map, A, ensure_map
    ensure_map("KnossaAmnisos", 40, 30, "amnisos", "MAP_TYPE_TOWN", "MAPSEC_AMNISOS", "MUS_ICHOR_AKTI")
    m = Map("KnossaAmnisos", "amnisos", 40, 30)
    m.piece("quay", "S", 4, 6)
    m.build("knossa_amnisos", starts=[(20, 7)])
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kythera_maps as KM  # noqa: E402
import knossa_tiles as KN  # noqa: E402

A = KM.A
ROOT = KM.ROOT
GROUP = "gMapGroup_Knossa"
SYMBOLS = {"amnisos": "gTileset_Amnisos", "bull_road": "gTileset_BullRoad",
           "palace_minos": "gTileset_PalaceMinos", "palace_rooms": "gTileset_PalaceRooms"}


def const_name(name):
    return re.sub(r"(?<=[a-z])(?=[A-Z])", "_", name).upper()


def ensure_map(name, w, h, tileset, map_type, mapsec, music, primary="aethos", weather=None, **extra):
    """Register `name` if it isn't yet; always refresh its header fields."""
    layouts_p = ROOT / "data/layouts/layouts.json"
    lay = json.loads(layouts_p.read_text())
    lid = "LAYOUT_" + const_name(name)
    if not any(l.get("id") == lid for l in lay["layouts"]):
        d = ROOT / "data/layouts" / name
        d.mkdir(parents=True, exist_ok=True)
        np.full(w * h, A.GRASS | (3 << 12), np.uint16).astype("<u2").tofile(d / "map.bin")
        np.array([A.GRASS] * 4, np.uint16).astype("<u2").tofile(d / "border.bin")
        lay["layouts"].append({"id": lid, "name": f"{name}_Layout", "width": w, "height": h,
                               "primary_tileset": KM.PRIMARY_DIR[primary], "secondary_tileset": SYMBOLS[tileset],
                               "border_filepath": f"data/layouts/{name}/border.bin",
                               "blockdata_filepath": f"data/layouts/{name}/map.bin", "layout_version": "emerald"})
        layouts_p.write_text(json.dumps(lay, indent=2, ensure_ascii=False) + "\n")
    outdoors = map_type in ("MAP_TYPE_TOWN", "MAP_TYPE_CITY", "MAP_TYPE_ROUTE")
    md = ROOT / "data/maps" / name
    mp = md / "map.json"
    if not mp.exists():
        md.mkdir(parents=True, exist_ok=True)
        mp.write_text(json.dumps({
            "id": "MAP_" + const_name(name), "name": name, "layout": lid, "music": music,
            "region": "REGION_HOENN", "region_map_section": mapsec, "requires_flash": False,
            "weather": "WEATHER_SUNNY", "map_type": map_type, "allow_cycling": outdoors,
            "allow_escaping": False, "allow_running": True, "show_map_name": outdoors,
            "battle_scene": "MAP_BATTLE_SCENE_NORMAL", "connections": None, "object_events": [],
            "warp_events": [], "coord_events": [], "bg_events": []}, indent=2) + "\n")
        if not (md / "scripts.pory").exists():
            (md / "scripts.pory").write_text(f"mapscripts {name}_MapScripts {{}}\n")
        gi = ROOT / ".gitignore"
        line = f"data/maps/{name}/scripts.inc"
        if line not in gi.read_text().split("\n"):
            with gi.open("a") as f:
                f.write(line + "\n")
        gp = ROOT / "data/maps/map_groups.json"
        groups = json.loads(gp.read_text())
        if GROUP not in groups:
            groups[GROUP] = []
            groups["group_order"].append(GROUP)
        if name not in groups[GROUP]:
            groups[GROUP].append(name)
        gp.write_text(json.dumps(groups, indent=2, ensure_ascii=False) + "\n")
        inc = ROOT / "data/ichor_maps.inc"
        with inc.open("a") as f:
            f.write(f'\t.include "data/maps/{name}/scripts.inc"\n')
    mj = json.loads(mp.read_text())
    mj.update({"music": music, "region_map_section": mapsec, "map_type": map_type,
               "weather": weather or ("WEATHER_SUNNY" if outdoors else "WEATHER_NONE"),
               "allow_cycling": outdoors, "show_map_name": outdoors})
    mj.update(extra)
    mp.write_text(json.dumps(mj, indent=2, ensure_ascii=False) + "\n")


class Map(KM.Map):
    def __init__(self, name, tileset, w, h, fill=A.GRASS, primary="aethos"):
        self.name, self.ts, self.w, self.h, self.primary = name, tileset, w, h, primary
        self.cat = KN.TILESETS[tileset]
        self.mid = np.full((h, w), fill, np.uint16)
        self.solid = np.zeros((h, w), bool)
        self.pattr = KM._attrs(f"data/tilesets/primary/{primary}/porytiles_bin/metatile_attributes.bin")
        self.sattr = KM._attrs(f"data/tilesets/secondary/{tileset}/porytiles_bin/metatile_attributes.bin")
        self.objects, self.warps, self.coords, self.bgs, self.connections = [], [], [], [], []
        self.seams = []
        self.border = [A.SEA] * 4
        self.header = {}
        self.forced_open = set()
        self.elev = {}          # (x, y) -> elevation, over the default land/sea one

    def encode(self):
        out = super().encode()
        for (x, y), e in self.elev.items():
            out[y, x] = (int(out[y, x]) & 0x0FFF) | (e << 12)
        return out

    def raise_ground(self, cells, elev=4, joins=()):
        """A raised level: `cells` at `elev`; `joins` (stairs, ladders) at 0, which
        meets any level."""
        for c in cells:
            self.elev[c] = elev
        for c in joins:
            self.elev[c] = 0

    def id(self, key, name):
        s = self.s(key)
        cx, cy = s["names"][name]
        return s["ids"][cy][cx]

    def front(self, key, x, y):
        """A house front from the tileset's fronts (rows of `house` piece names)."""
        f = self.cat["fronts"][key]
        for j, row in enumerate(f["rows"]):
            for i, n in enumerate(row):
                self.piece("house", n, x + i, y + j)

    def tall(self, cells):
        """Aethos tall grass over a set of cells; an olive's crown tip over it is kept."""
        for (x, y) in cells:
            self.set(x, y, A.TALL, False)

    def grass_mix(self, x0, y0, x1, y1, salt=0, accents=(A.ANEMONE,)):
        """Open ground with aethos's grass and a few clustered accents (STYLE §4.2):
        only cells still plain grass change."""
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if not self.ok(x, y) or int(self.mid[y, x]) != A.GRASS:
                    continue
                h = KM._hash(x // 2, y // 2, salt)
                if h < 40 and KM._hash(x, y, salt + 1) < 600:
                    self.set(x, y, accents[KM._hash(x, y, salt + 2) % len(accents)], False)


def quay(m, mask, key="quay", top=None, land=()):
    """A stone quay or mole over a set of cells: cells beside sea (any cell not
    in the mask or `land`) take the quay kit's edge, named by where the sea is;
    the rest is aethos's limestone path (or `top(x, y)`)."""
    mask = set(mask)
    land = set(land)

    def sea(x, y):
        return (x, y) not in mask and (x, y) not in land
    for (x, y) in mask:
        n, s, e, w = sea(x, y - 1), sea(x, y + 1), sea(x + 1, y), sea(x - 1, y)
        name = ("out_NW" if n and w else "out_NE" if n and e else "out_SW" if s and w else
                "out_SE" if s and e else "N" if n else "S" if s else "E" if e else "W" if w else
                "in_NE" if sea(x + 1, y - 1) else "in_NW" if sea(x - 1, y - 1) else
                "in_SE" if sea(x + 1, y + 1) else "in_SW" if sea(x - 1, y + 1) else None)
        if name:
            m.piece(key, name, x, y)
        else:
            m.set(x, y, top(x, y) if top else A.PATH, False)


def pave(m, cells, salt=0):
    """Amnisos's quay flagstones over cells, in a staggered mix with a worn slab."""
    for (x, y) in cells:
        k = KM._hash(x, y, salt) % 13
        n = "worn" if k == 0 else ("A", "B", "C")[(x + 2 * y + (k > 7)) % 3]
        m.piece("flags", n, x, y)


def wall_run(m, x0, x1, y, key="wall", solid_top=False, gaps=()):
    """A dry-stone wall west to east: the face row at y, its coping at y - 1."""
    for x in range(x0, x1 + 1):
        if x in gaps:
            continue
        n = "L" if x == x0 or (x - 1) in gaps else ("R" if x == x1 or (x + 1) in gaps else
                                                     ("M2" if (x * 5 + y) % 4 == 2 else "M"))
        m.piece(key, n, x, y)
        tn = "top" + ("_L" if n == "L" else "_R" if n == "R" else "_M2" if n == "M2" else "")
        m.piece(key, tn, x, y - 1, solid=True if solid_top else None)


def dump(ts, keys):
    for k in keys:
        s = KN.TILESETS[ts]["structures"][k]
        print(ts, k, s["w"], s["h"], " ".join(f"{n}:{s['walk'][y][x]}" for n, (x, y) in
                                              sorted(s["names"].items(), key=lambda t: (t[1][1], t[1][0]))))


def register_all():
    """Re-register every Knossa map in map_groups.json and ichor_maps.inc (after a
    merge kept only the other side's lists)."""
    maps = sorted(p.name for p in (ROOT / "data/maps").iterdir() if p.name.startswith("Knossa"))
    gp = ROOT / "data/maps/map_groups.json"
    g = json.loads(gp.read_text())
    present = {m for k in g["group_order"] for m in g[k]}
    if GROUP not in g:
        g[GROUP] = []
        g["group_order"].append(GROUP)
    g[GROUP] += [m for m in maps if m not in present]
    gp.write_text(json.dumps(g, indent=2, ensure_ascii=False) + "\n")
    inc = ROOT / "data/ichor_maps.inc"
    text = inc.read_text()
    for m in maps:
        line = f'\t.include "data/maps/{m}/scripts.inc"\n'
        if line not in text:
            text += line
    inc.write_text(text)
    print("registered", len(maps), "Knossa maps")


if __name__ == "__main__":
    if sys.argv[1] == "--register":
        register_all()
    else:
        dump(sys.argv[1], sys.argv[2:])
