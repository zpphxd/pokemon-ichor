def mid(tileset, key, name=None, x=0, y=0):
    """The metatile id of a named piece (or of cell (x, y) of a structure)."""
    s = TILESETS[tileset]['structures'][key]
    if name is not None:
        x, y = s['names'][name]
    return s['ids'][y][x]


def walk(tileset, key, name=None, x=0, y=0):
    """The walk code of a named piece: X . T G J D W P S (see the catalogs)."""
    s = TILESETS[tileset]['structures'][key]
    if name is not None:
        x, y = s['names'][name]
    return s['walk'][y][x]


def front(tileset, key):
    """A house front: rows of metatile ids (None where it leaves the ground)."""
    return TILESETS[tileset]['fronts'][key]['ids']


