class Maze:
    """A maze on an nx x ny grid of nodes. Each node is a 2x2 floor at cells
    (PITCH*x + 2, PITCH*y + 2); a passage between neighbours opens the 2-cell wall
    between them. `rooms` merge blocks of nodes into chambers."""

    def __init__(self, nx, ny, seed=1):
        self.nx, self.ny = nx, ny
        self.rng = random.Random(seed)
        self.edges = set()          # frozenset({a, b})
        self.rooms = []             # (x0, y0, x1, y1) in nodes, inclusive
        self.off = set()            # nodes left solid (no maze there)
        self.room_of = {}

    def nbrs(self, n):
        x, y = n
        for dx, dy in DIRS4:
            m = (x + dx, y + dy)
            if 0 <= m[0] < self.nx and 0 <= m[1] < self.ny and m not in self.off:
                yield m

    def room(self, x0, y0, x1, y1):
        r = (x0, y0, x1, y1)
        self.rooms.append(r)
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.room_of[(x, y)] = r
                if x < x1:
                    self.edges.add(frozenset({(x, y), (x + 1, y)}))
                if y < y1:
                    self.edges.add(frozenset({(x, y), (x, y + 1)}))
        return r

    def link(self, a, b):
        self.edges.add(frozenset({a, b}))

    def unlink(self, a, b):
        self.edges.discard(frozenset({a, b}))

    def nodes(self):
        return [(x, y) for y in range(self.ny) for x in range(self.nx) if (x, y) not in self.off]

    def deg(self, n):
        return sum(1 for m in self.nbrs(n) if frozenset({n, m}) in self.edges)

    def carve(self, start, keep=()):
        """A depth-first spanning maze over every node not yet connected, then
        nothing else: braid() adds the loops. `keep` edges stay closed."""
        keep = {frozenset(e) for e in keep}
        seen = {start}
        # rooms are already internally joined: treat each room as visited together
        def absorb(n):
            r = self.room_of.get(n)
            if r:
                for y in range(r[1], r[3] + 1):
                    for x in range(r[0], r[2] + 1):
                        seen.add((x, y))
        absorb(start)
        stack = [start]
        while stack:
            n = stack[-1]
            opts = [m for m in self.nbrs(n) if m not in seen and frozenset({n, m}) not in keep]
            if not opts:
                stack.pop()
                continue
            m = self.rng.choice(opts)
            self.link(n, m)
            seen.add(m)
            absorb(m)
            stack.append(m)
        return seen

    def braid(self, fraction, keep_dead=(), keep=()):
        """Open a wall at `fraction` of the dead ends (making loops), never at the
        dead ends in keep_dead, never across `keep` edges."""
        keep = {frozenset(e) for e in keep}
        dead = [n for n in self.nodes() if self.deg(n) == 1 and n not in keep_dead]
        self.rng.shuffle(dead)
        for n in dead[:int(len(dead) * fraction)]:
            if self.deg(n) != 1:
                continue
            opts = [m for m in self.nbrs(n) if frozenset({n, m}) not in self.edges
                    and frozenset({n, m}) not in keep]
            if opts:
                opts.sort(key=lambda m: self.deg(m))
                self.link(n, opts[0])

    def crossings(self, k, keep=(), avoid=()):
        """Open k more walls between corridor nodes that are not yet joined, so
        corridors cross: more junctions and loops. Never across `keep`, never
        into a node in `avoid`."""
        keep = {frozenset(e) for e in keep}
        cands = []
        for n in self.nodes():
            for dx, dy in ((1, 0), (0, 1)):
                m = (n[0] + dx, n[1] + dy)
                e = frozenset({n, m})
                if m in self.off or not (m[0] < self.nx and m[1] < self.ny) or e in self.edges or e in keep:
                    continue
                if n in avoid or m in avoid:
                    continue
                if self.deg(n) == 2 and self.deg(m) == 2:
                    cands.append((n, m))
        self.rng.shuffle(cands)
        for n, m in cands[:k]:
            self.link(n, m)

    # --- metrics, on the graph whose nodes are chambers and maze nodes -----------------
    def graph(self):
        rep = {}
        for n in self.nodes():
            rep[n] = self.room_of.get(n, n)
        adj = {}
        for e in self.edges:
            a, b = tuple(e)
            ra, rb = rep[a], rep[b]
            if ra == rb:
                continue
            adj.setdefault(ra, set()).add(rb)
            adj.setdefault(rb, set()).add(ra)
        for r in set(rep.values()):
            adj.setdefault(r, set())
        return adj

    def metrics(self):
        adj = self.graph()
        V = len(adj)
        E = sum(len(v) for v in adj.values()) // 2
        # components
        comp, seen = 0, set()
        for s in adj:
            if s in seen:
                continue
            comp += 1
            q = [s]
            seen.add(s)
            while q:
                n = q.pop()
                for m in adj[n]:
                    if m not in seen:
                        seen.add(m)
                        q.append(m)
        junctions = [n for n, v in adj.items() if len(v) >= 3]
        dead = [n for n, v in adj.items() if len(v) == 1]
        # longest straight run of corridor nodes with degree 2 in line
        run = 0
        for n in self.nodes():
            if n in self.room_of:
                continue
            for dx, dy in ((1, 0), (0, 1)):
                k, m = 0, n
                while (m not in self.room_of and frozenset({m, (m[0] + dx, m[1] + dy)}) in self.edges
                       and self.deg(m) == 2 if k else True):
                    nxt = (m[0] + dx, m[1] + dy)
                    if frozenset({m, nxt}) not in self.edges:
                        break
                    k += 1
                    m = nxt
                    if m in self.room_of or self.deg(m) != 2:
                        break
                run = max(run, k)
        return {"nodes": V, "edges": E, "loops": E - V + comp, "components": comp,
                "junctions": len(junctions), "dead_ends": len(dead), "dead": dead,
                "longest_straight_cells": run * PITCH + 2}

    def sketch(self):
        """The graph as ASCII: + a node, # a chamber, D a dead end, J a junction."""
        rows = []
        for y in range(self.ny):
            line, below = "", ""
            for x in range(self.nx):
                n = (x, y)
                if n in self.off:
                    ch = " "
                elif n in self.room_of:
                    ch = "#"
                else:
                    d = self.deg(n)
                    ch = "D" if d == 1 else ("J" if d >= 3 else "+")
                line += ch
                line += "-" if frozenset({n, (x + 1, y)}) in self.edges else " "
                below += ("|" if frozenset({n, (x, y + 1)}) in self.edges else " ") + " "
            rows += [line.rstrip(), below.rstrip()]
        return "\n".join(rows)

    def to_grid(self, w, h, cave=lambda x, y: False):
        """The character grid: walls '#' (or '%' where cave(x, y)), floors '.' (or
        ',' in the cave)."""
        g = [["%" if cave(x, y) else "#" for x in range(w)] for y in range(h)]

        def floor(x, y):
            if 0 < x < w and 0 < y < h:
                g[y][x] = "," if cave(x, y) else "."
        for (x, y) in self.nodes():
            for j in range(2):
                for i in range(2):
                    floor(PITCH * x + 2 + i, PITCH * y + 2 + j)
        for e in self.edges:
            (ax, ay), (bx, by) = sorted(tuple(e))
            if ay == by:            # east-west: open the two columns between
                for i in range(2):
                    for j in range(2):
                        floor(PITCH * ax + 4 + i, PITCH * ay + 2 + j)
            else:
                for i in range(2):
                    for j in range(2):
                        floor(PITCH * ax + 2 + i, PITCH * ay + 4 + j)
        # chambers: open their inner wall crossings too
        for (x0, y0, x1, y1) in self.rooms:
            for y in range(PITCH * y0 + 2, PITCH * y1 + 4):
                for x in range(PITCH * x0 + 2, PITCH * x1 + 4):
                    floor(x, y)
        return g


def cave_grid(mz, w, h, cave_nodes, seed=1, erode=0.35):
    """The character grid with the cave taking the nodes in cave_nodes: their
    floors are earth, the walls round them raw rock, and the rock is eaten
    back at random wherever that leaves it two cells thick, so cave passages
    bulge and wander while the masonry stays straight."""
    rng = random.Random(seed)

    def touching(v):
        i = (v - 2) // PITCH
        return (i,) if (v - 2) % PITCH < 2 else (i, i + 1)

    def in_cave(x, y):
        return any((i, j) in cave_nodes for i in touching(x) for j in touching(y))

    g = mz.to_grid(w, h, in_cave)
    # the rock, eaten back
    cands = []
    for y in range(1, h - 1):
        for x in range(1, w - 1):
            if g[y][x] == "%" and any(g[y + dy][x + dx] == "," for dx, dy in DIRS4):
                cands.append((x, y))
    rng.shuffle(cands)
    for (x, y) in cands[:int(len(cands) * erode)]:
        if g[y][x] != "%":
            continue
        ok = True
        for dx, dy in DIRS4:
            if g[y + dy][x + dx] == ",":
                # keep the rock behind it at least two thick (or the map's edge)
                bx, by = x - dx, y - dy
                for k in range(2):
                    cx, cy = bx - dx * k, by - dy * k
                    if 0 <= cx < w and 0 <= cy < h and g[cy][cx] not in "%#":
                        ok = False
        if ok and 1 < x < w - 2 and 1 < y < h - 2:
            g[y][x] = ","
    return g


def cell(n, dx=0, dy=0):
    """The top-left floor cell of maze node n, offset."""
    return (PITCH * n[0] + 2 + dx, PITCH * n[1] + 2 + dy)


