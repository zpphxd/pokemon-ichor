"""Shared builder for the Labyrinth's upper rings (design/LABYRINTH_MAZE.md).

Every ring is a real maze cut through two materials: Daedalus's masonry and the
karst cave he built it into. A ring is planned on a coarse grid (one node every
PITCH cells: a corridor two cells wide, walls two cells thick), carved as a
braided maze with stamped chambers, then laid from a character grid:

    #  masonry wall (the corridor kit's autotile)    .  masonry floor (dark slabs)
    %  cave rock (the cave kit's autotile)           ,  cave earth    ;  gravel
    ~  the underground stream (Surf)                 o  a chasm
    -  a beam across a chasm, east-west              |  a beam, north-south

Every walkable cell takes Ariadne's thread: the slab halves, earth, gravel and
beams are all registered thread floors (eight is the engine's limit), so the
thread runs unbroken through house and cave alike.

    from labyrinth_lib import LMap, Maze
"""
