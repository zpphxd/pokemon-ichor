def map_exists(map_id):
    """True if a map with this MAP_ id is registered (data/maps/*/map.json)."""
    import json
    for p in (ROOT / "data/maps").glob("*/map.json"):
        try:
            if json.loads(p.read_text()).get("id") == map_id:
                return True
        except ValueError:
            pass
    return False


def dest(map_id, fallback):
    """A warp's destination: map_id once the other builder's map exists, else
    the fallback (map, warp) so the build stays green (Labyrinth_System.md lists
    every such seam)."""
    return (map_id, None) if map_exists(map_id) else fallback


def thread_floor_list(kinds):
    """[(floor, first twin)] for the floors a ring uses."""
    out = list(LT.thread_floors(TS))                       # the slab halves
    for k in kinds:
        f = mid("cave_floors", k) if k != "plate" else mid("plate", "plate")
        out.append((f, f + 1))
    return out


def _cave_name(names, key):
    for k in CK.fallbacks(key):
        if k in names:
            return k
    raise KeyError(key)


