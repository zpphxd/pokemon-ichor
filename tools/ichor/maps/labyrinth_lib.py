class LMap(Map):
    def __init__(self, name, w, h, header):
        self.name, self.ts, self.w, self.h, self.primary = name, TS, w, h, "oikos"
        self.cat = LT.TILESETS[TS]
        self.mid = np.full((h, w), ROCK_TOP, np.uint16)
        self.solid = np.ones((h, w), bool)
        self.pattr = _attrs("data/tilesets/primary/oikos/porytiles_bin/metatile_attributes.bin")
        self.sattr = _attrs(f"data/tilesets/secondary/{TS}/porytiles_bin/metatile_attributes.bin")
        self.objects, self.warps, self.coords, self.bgs, self.connections = [], [], [], [], []
        self.seams = []
        self.border = [ROCK_TOP] * 4
        self.header = header
        self.forced_open = set()
        self.g = [["#"] * w for _ in range(h)]
        self.arrivals = set()
        self.anchors = []            # (x, y, THREAD_ANCHOR_*)
        self.cracks = []             # (x, y, flag, floor char)
        self.floors_used = set()
        self.gen = []                # extra ON_LOAD lines
        self.stops = set()           # walkable cells that take no thread on purpose

    # --- the grid -----------------------------------------------------------------------
    def setc(self, x, y, ch):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.g[y][x] = ch

    def fill(self, x0, y0, x1, y1, ch):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.setc(x, y, ch)

    def at(self, x, y):
        if 0 <= x < self.w and 0 <= y < self.h:
            return self.g[y][x]
        return "#"

    def is_wall(self, x, y):
        return self.at(x, y) in WALLS

    def floor_id(self, x, y, ch=None):
        ch = ch or self.at(x, y)
        if ch in ".A":
            return LT.floor(x, y, TS)
        return CAVE_FLOOR[ch]

    def lay(self):
        """Autotile the whole grid into metatiles."""
        wall = [[self.is_wall(x, y) for x in range(self.w)] for y in range(self.h)]
        cg = [["#" if wall[y][x] else ("~" if self.g[y][x] in "~o-|" else ".") for x in range(self.w)]
              for y in range(self.h)]
        kinds = CK.classify(cg)
        rock_names = ST["cave_rock"]["names"]
        for y in range(self.h):
            for x in range(self.w):
                ch = self.g[y][x]
                if ch == "#":
                    self.set(x, y, mid("walls", LT.classify(wall, x, y)), True)
                elif ch == "%":
                    key = CK.cell_key(cg, kinds, x, y, "labyrinth")
                    self.set(x, y, mid("cave_rock", _cave_name(rock_names, key)), True)
                elif ch in "~o":
                    self._region(x, y, ch)
                elif ch in FLOORS:
                    if ch in ",;-|":
                        self.floors_used.add({",": "earth", ";": "gravel", "-": "beam_h",
                                              "|": "beam_v"}[ch])
                    if ch == "A":
                        self.set(x, y, LT.mid(TS, LT.piece(TS, "anchor", x, y), "ring"), False)
                    else:
                        self.set(x, y, self.floor_id(x, y), False)
                else:
                    raise ValueError(f"{self.name}: unknown cell {ch!r} at ({x},{y})")

    def _region(self, x, y, ch):
        same = "~" if ch == "~" else "o-|"
        def out(xx, yy):
            return self.at(xx, yy) not in same
        N, S, W, E = out(x, y - 1), out(x, y + 1), out(x - 1, y), out(x + 1, y)
        nubs = [n for n, (dx, dy), a, b in (("nw", (-1, -1), N, W), ("ne", (1, -1), N, E),
                                             ("sw", (-1, 1), S, W), ("se", (1, 1), S, E))
                if not a and not b and out(x + dx, y + dy)]
        key = CK.water_key(N, S, W, E, nubs)
        if ch == "~":
            names = ST["cave_water"]["names"]
            self.set(x, y, mid("cave_water", _cave_name(names, key)), False)
        else:
            names = ST["cave_pit"]["names"]
            self.set(x, y, mid("cave_pit", _cave_name(names, "pit" + key[5:])), True)

    # --- pieces ---------------------------------------------------------------------------
    def put(self, key, x, y, cells=None, solid=None):
        """A piece with its top-left at (x, y), on the right parity twin."""
        s = ST[key]
        odd = ST.get(key + "_odd") if (x + y) % 2 else None
        first = odd["twin_of"][1] if odd else s["h"]
        for j in range(s["h"]):
            for i in range(s["w"]):
                if cells is not None and (i, j) not in cells:
                    continue
                if odd and j >= first:
                    m, wk = odd["ids"][j - first][i], odd["walk"][j - first][i]
                else:
                    m, wk = s["ids"][j][i], s["walk"][j][i]
                self.set(x + i, y + j, m, (wk == "X") if solid is None else solid)
                if wk != "X":
                    self.stops.add((x + i, y + j))

    def named(self, key, name, x, y, solid=True):
        self.set(x, y, mid(key, name), solid)

    def anchor(self, x, y, name):
        self.g[y][x] = "A"
        self.set(x, y, LT.mid(TS, LT.piece(TS, "anchor", x, y), "ring"), False)
        self.anchors.append((x, y, name))

    def stairs(self, x, y, which):
        """A two-cell stairway in a masonry face row, top-left (x, y)."""
        self.named("stairs", f"{which}_l", x, y, False)
        self.named("stairs", f"{which}_r", x + 1, y, False)
        self.stops |= {(x, y), (x + 1, y)}

    def crack(self, x, y, name, flag):
        self.named("cracked", name, x, y)
        self.cracks.append((x, y, flag))

    # --- events -----------------------------------------------------------------------------
    def arrival(self, x, y):
        i = self.warp(x, y, "MAP_" + re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", self.name).upper(), 0)
        self.arrivals.add(i)
        return i

    def item(self, x, y, item, flag):
        return self.obj("ITEM_BALL", x, y, "Common_EventScript_FindItem", flag=flag, item=item)

    # --- checks ------------------------------------------------------------------------------
    def check(self, starts, must_reach=(), blockers=(), extra=()):
        errors, reach = Map.check(self, starts, must_reach, blockers, extra)
        keep = []
        for e in errors:
            m = re.match(r"warp at \((\d+),(\d+)\) is on (\w+), not a door", e)
            if m and any(self.warps[i]["x"] == int(m.group(1)) and self.warps[i]["y"] == int(m.group(2))
                         for i in self.arrivals):
                continue
            keep.append(e)
        floors = set()
        for f, t in thread_floor_list(sorted(self.floors_used) + (["plate"] if "plate" in self.floors_used else [])):
            floors |= {f} | set(range(t, t + 10))
        rings = {mid("anchor", "ring"), LT.mid(TS, "anchor_odd", "ring")}
        for (x, y) in reach:
            m = int(self.mid[y, x])
            if self.behavior(m) in DOORS or (x, y) in self.stops or self.behavior(m) == "MB_POND_WATER":
                continue
            if m not in floors and m not in rings:
                keep.append(f"({x},{y}) is walkable but takes no thread (0x{m:03X})")
        return keep, reach

    def straight_runs(self, reach, limit=8):
        """Cells where a corridor runs more than `limit` cells without a turn,
        junction or feature (a cell with an event counts as a feature)."""
        feats = {(o["x"], o["y"]) for o in self.objects} | {(b["x"], b["y"]) for b in self.bgs} \
            | {(c["x"], c["y"]) for c in self.coords} | getattr(self, "features", set())
        bad = []
        for (x, y) in reach:
            for dx, dy in ((1, 0), (0, 1)):
                if (x - dx, y - dy) in reach:
                    continue
                k, cx, cy = 0, x, y
                while (cx, cy) in reach:
                    side = sum(((cx + sx, cy + sy) in reach) for sx, sy in ((dy, dx), (-dy, -dx)))
                    if side == 2 or (cx, cy) in feats:     # an open side both ways: a room
                        k = 0
                    else:
                        k += 1
                    if k > limit:
                        bad.append((cx - dx * limit, cy - dy * limit, dx, dy))
                        break
                    cx, cy = cx + dx, cy + dy
        return bad

    def break_runs(self, starts, seed=5, limit=40):
        """Give every long straight corridor something to look at: a carved
        niche (plain, a goddess's shrine, a lamp gone out) in a masonry face
        beside it, or a stalagmite or boulder on one lane of a cave passage
        (kept only if nothing is cut off)."""
        rng = random.Random(seed)
        self.features = getattr(self, "features", set())
        faces = {mid("walls", n) for n in ST["walls"]["names"] if n.startswith("face")}
        cave_faces = {v for k, v in ((k, ST["cave_rock"]["ids"][xy[1]][xy[0]])
                                     for k, xy in ST["cave_rock"]["names"].items()) if k.startswith("fb")}
        niches = ["back", "back", "shrine", "lamp_out"]
        rocks = ["stalagmite", "stalagmites", "boulder", "stalagmite", "rock_pile"]
        for _ in range(limit):
            reach = self.reach(starts, extra=self.forced_open)
            runs = self.straight_runs(reach)
            if not runs:
                return
            x, y, dx, dy = runs[0]
            cx, cy = x + dx * 5, y + dy * 5
            done = False
            if dx == 0 and self.at(cx, cy) == "." and self.at(cx, cy + 1) == ".":
                # a red Minoan column on one lane of a north-south corridor
                before = len(reach)
                self.solid[cy, cx] = self.solid[cy + 1, cx] = True
                after = self.reach(starts, extra=self.forced_open)
                if len(after) == before - 2:
                    self.put("tomb_pillar", cx, cy)
                    self.features |= {(cx + a, cy + b) for a in (-1, 0, 1) for b in (-1, 0, 1, 2)}
                    continue
                self.solid[cy, cx] = self.solid[cy + 1, cx] = False
            for sx, sy in ((0, -1), (0, -2)):
                wx, wy = cx + sx, cy + sy
                if not self.ok(wx, wy):
                    continue
                m = int(self.mid[wy, wx])
                if m in faces and (sy == -1 or self.walkable(cx, cy - 1)):
                    self.named("niche", rng.choice(niches), wx, wy)
                    self.features.add((cx, cy))
                    done = True
                    break
            if not done and self.at(cx, cy) in ",;":
                before = len(reach)
                self.solid[cy, cx] = True
                after = self.reach(starts, extra=self.forced_open)
                if len(after) == before - 1 and all(self.at(cx + a, cy + b) in ",;" for a, b in ((dy, dx), (-dy, -dx)) if True)\
                        or len(after) == before - 1:
                    self.put(rng.choice(rocks), cx, cy)
                    self.solid[cy, cx] = True
                    self.features |= {(cx + a, cy + b) for a, b in DIRS4}
                    done = True
                else:
                    self.solid[cy, cx] = False
            if not done:
                self.features.add((cx, cy))     # nothing fits: let the corridor be (reported)
                print(f"{self.name}: no feature fits the run at ({x},{y}); left plain")

    # --- the generated ON_LOAD block ----------------------------------------------------------
    def gen_block(self):
        L = [f"script {self.name}_EventScript_Register {{",
             "    // the floors that take Ariadne's thread, each with its first twin"]
        kinds = sorted(self.floors_used)
        for f, t in thread_floor_list(kinds):
            L += [f"    setvar(VAR_0x8004, 0x{f:03X})", f"    setvar(VAR_0x8005, 0x{t:03X})",
                  "    special(Ichor_AddThreadFloor)"]
        for (x, y, n) in self.anchors:
            L += [f"    setvar(VAR_0x8004, {x})", f"    setvar(VAR_0x8005, {y})",
                  f"    setvar(VAR_0x8006, {n})", "    special(Ichor_AddThreadAnchor)"]
        for (x, y, flag) in self.cracks:
            fl = self.floor_id(x, y, ".")
            L += [f"    setvar(VAR_0x8004, {x})", f"    setvar(VAR_0x8005, {y})",
                  f"    setvar(VAR_0x8006, {flag})", f"    setvar(VAR_0x8007, 0x{fl:03X})",
                  "    special(Ichor_AddCrackedWall)",
                  f"    if (flag({flag})) {{", f"        setmetatile({x}, {y}, 0x{fl:03X}, FALSE)", "    }"]
        L.append("}")
        L += ["", "// The ring's state, drawn on load and after every change: lit braziers, opened",
              "// doors and gates. Ichor_DrawThread goes after it.",
              f"script {self.name}_EventScript_DrawState {{"]
        L += ["    " + s for s in self.gen] or ["    end"]
        L.append("}")
        L += getattr(self, "extra_scripts", [])
        return "\n".join(L)

    def write_scripts(self):
        p = ROOT / "data/maps" / self.name / "scripts.pory"
        t = p.read_text() if p.exists() else ""
        block = self.gen_block()
        if GEN_BEGIN in t:
            t = t[:t.index(GEN_BEGIN)] + GEN_BEGIN + "\n" + block + "\n" + GEN_END + t[t.index(GEN_END) + len(GEN_END):]
        else:
            t = t.rstrip("\n") + "\n\n" + GEN_BEGIN + "\n" + block + "\n" + GEN_END + "\n"
        p.write_text(t)

    def write(self):
        clean = []
        for i, w in enumerate(self.warps):
            clean.append({k: v for k, v in w.items() if k != "unreached_ok"})
        saved, self.warps = self.warps, clean
        try:
            Map.write(self)
        finally:
            self.warps = saved

    def build(self, stem, starts, must_reach=(), views=(), blockers=(), extra=(), render=True):
        for i in self.arrivals:
            self.warps[i]["unreached_ok"] = True
        errors, reach = self.check(starts, must_reach, blockers, extra)
        runs = self.straight_runs(reach)
        self.write()
        self.write_scripts()
        if render:
            self.render(stem, views)
        for e in errors:
            print(f"{self.name} CHECK: {e}")
        if runs:
            print(f"{self.name} STRAIGHT: {len(runs)} runs over 8 cells, first at {runs[:4]}")
        print(f"{self.name}: {self.w}x{self.h}, {len(self.objects)} objects, {len(self.warps)} warps, "
              f"{len(self.coords)} triggers, {len(self.bgs)} bg events; "
              f"{'checks pass' if not errors else f'{len(errors)} problems'}")
        return errors, reach
