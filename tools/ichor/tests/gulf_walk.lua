local L = dofile("tools/ichor/tests/engine_lib.lua")
local S = L.S
for k, v in pairs(dofile(L.OUT .. "gulf_symbols.lua")) do S.SCRIPTS[k] = v end
local function cross(dir, map, name)
    L.leaveEdge(dir, map)
    L.expect(L.mapId() == map, "crossed the seam: " .. name)
    L.shot(name)
end
local function enter(map, name)
    L.useWarp(map)
    L.expect(L.mapId() == map, "went through: " .. name)
    L.shot(name)
end
L.start(function()
    L.quickstart()
    L.runHeader("Gulf_SetupHeader")
    cross("down", S.MAP_R9, "route9_from_lebadeia")
    cross("up", S.MAP_LEBADEIA, "lebadeia_from_route9")
    cross("down", S.MAP_R9, "route9_again")
    L.talk(L.npc("Route9_ParnassosCrossroads_EventScript_Spring"))
    L.expect(L.getFlag(S.FLAG_SPRING), "the shepherds' spring heals and gives its water")
    cross("down", S.MAP_KIRRHA, "kirrha")
    L.talk(L.npc("Kirrha_EventScript_Healer"))
    L.expect(L.idle(), "Kirrha's healer returns control")
    enter(S.MAP_HOSTEL, "hostel")
    L.talk(L.npc("Kirrha_PilgrimsHostel_EventScript_Xenarete"))
    L.expect(L.getFlag(S.FLAG_WATER) and L.itemCount(S.ITEM_WATER) >= 1, "Xenarete gives the Kastalian water")
    L.talk(L.npc("Kirrha_PilgrimsHostel_EventScript_Hesychia"))
    L.expect(L.getFlag(S.FLAG_ASKED) and not L.getFlag(S.FLAG_BEE), "Hesychia asks for her gold bee")
    enter(S.MAP_KIRRHA, "hostel_door")
    cross("up", S.MAP_R9, "route9_from_kirrha")
    enter(S.MAP_CAVE, "korykian_cave")
    L.talk(L.sign("Route9_KorykianCave_EventScript_Brazier"), { answers = { "yes" } })
    L.expect(L.getFlag(S.FLAG_BRAZIER), "the Torch lights Pan's brazier")
    L.shot("cave_lit")
    L.talk(L.sign("Route9_KorykianCave_EventScript_Niche"))
    L.expect(L.getFlag(S.FLAG_BEE), "the gold bee is in Pan's niche")
    enter(S.MAP_R9, "cave_mouth")
    cross("down", S.MAP_KIRRHA, "kirrha_again")
    enter(S.MAP_HOSTEL, "hostel_again")
    L.talk(L.npc("Kirrha_PilgrimsHostel_EventScript_Hesychia"))
    L.expect(L.getFlag(S.FLAG_BELL) and L.itemCount(S.ITEM_BELL) == 1, "Hesychia gives the hive bell")
    enter(S.MAP_KIRRHA, "hostel_door_again")
    L.talk(L.npc("Kirrha_EventScript_Captain"))
    L.expect(L.mapId() == S.MAP_FERRY, "boarded the trireme at Kirrha's quay")
    L.talk(L.npc("GulfTrireme_EventScript_Captain"))
    L.expect(L.mapId() == S.MAP_AIGION, "landed on Aigion's quay")
    L.shot("aigion")
    enter(S.MAP_HOMARION, "homarion")
    L.talk(L.npc("Aigion_Homarion_EventScript_Kleobis"))
    L.expect(L.getFlag(S.FLAG_OATH), "Kleobis gives the oarsman's bell")
    enter(S.MAP_AIGION, "homarion_door")
    L.talk(L.npc("Aigion_EventScript_Captain"))
    L.talk(L.npc("GulfTrireme_EventScript_Captain"))
    L.expect(L.mapId() == S.MAP_KIRRHA, "and back across to Kirrha")
    L.shot("kirrha_return")
end)
