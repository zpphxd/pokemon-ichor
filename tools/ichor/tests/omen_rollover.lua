local L = dofile("tools/ichor/tests/engine_lib.lua")
local S, K, emu = L.S, L.K, L.emu

local function present() return L.objectAt(S.LOCALID_KORANTHA) ~= nil end
local function savedWeather() return emu:read8(L.sb1() + S.OFF_SB1_WEATHER) end
local function currentWeather() return emu:read8(S.gWeather + S.OFF_WEATHER_CURRENT) end

local function nextDay(kind, entry)
  local day = L.getVar(S.VAR_DAYS)
  local map = L.mapId()
  L.setVar(S.VAR_0x8004, kind)
  L.setVar(S.VAR_0x8005, entry)
  L.runHeader("RolloverTest_AdvanceHeader")
  L.waitUntil(function() return L.getVar(S.VAR_DAYS) > day end, 9000, "the actual field clock's next day")
  L.wait(120)
  L.expect(L.mapId() == map, "the day changed without leaving the current map")
  L.expect(emu:read8(S.gLocalTime + S.OFF_TIME_HOURS) == 0, "the rollover occurs in the midnight hour")
end

L.start(function()
  L.quickstart()
  L.runHeader("RolloverTest_SetupHeader")
  nextDay(S.OMEN_GOOD_SIGN, S.OMEN_SIGN_BLESSING)
  L.expect(not present() and savedWeather() == S.WEATHER_NONE, "a normal day has no visitor or sun omen")
  nextDay(S.OMEN_VISITOR, S.OMEN_VISITOR_KORANTHA)
  L.expect(present() and not L.getFlag(S.FLAG_OMEN_KORANTHA), "the new day's visitor appears without map reentry")
  L.shot("visitor_arrived")
  L.runHeader("RolloverTest_ConsumeHeader")
  L.wait(180)
  L.expect(not present() and L.getFlag(S.FLAG_OMEN_KORANTHA), "a consumed visitor stays gone during the same day")
  nextDay(S.OMEN_VISITOR, S.OMEN_VISITOR_KORANTHA)
  L.expect(present(), "a later matching day sends a new visitor")
  L.setVar(S.VAR_0x8004, S.OMEN_WEATHER)
  L.setVar(S.VAR_0x8005, S.OMEN_WEATHER_ELEUSA_SUN)
  L.runHeader("RolloverTest_HeldHeader", { noSettle = true })
  L.wait(60)
  L.expect(present() and L.getFlag(S.FLAG_OMEN_KORANTHA) and savedWeather() == S.WEATHER_NONE,
           "an active script defers the pending visitor and weather refresh")
  L.setFlag(S.FLAG_ICHOR_FROZEN_HOUR, true)
  L.settle()
  L.expect(present() and savedWeather() == S.WEATHER_NONE, "the Frozen Hour keeps the pending day from changing the live world")
  L.setFlag(S.FLAG_ICHOR_FROZEN_HOUR, false)
  L.wait(120)
  L.expect(not present() and savedWeather() == S.WEATHER_DROUGHT, "the deferred refresh runs when field control and time return")
  nextDay(S.OMEN_VISITOR, S.OMEN_VISITOR_KORANTHA)
  L.expect(present(), "the next matching day restores the visitor after deferred expiry")
  nextDay(S.OMEN_WEATHER, S.OMEN_WEATHER_ELEUSA_SUN)
  L.expect(not present() and L.getFlag(S.FLAG_OMEN_KORANTHA), "an expired visitor disappears without talking to it")
  L.waitUntil(function() return currentWeather() == S.WEATHER_DROUGHT end, 600, "the live sun weather")
  L.expect(savedWeather() == S.WEATHER_DROUGHT, "saved and live weather both take the day's sun omen")
  L.shot("sun_arrived")
  nextDay(S.OMEN_GOOD_SIGN, S.OMEN_SIGN_BLESSING)
  L.waitUntil(function() return currentWeather() == S.WEATHER_NONE end, 600, "the sun weather to clear")
  L.expect(savedWeather() == S.WEATHER_NONE, "saved and live sun weather clear on the next day")
  L.shot("sun_expired")
  L.runHeader("RolloverTest_SpotHeader")
  nextDay(S.OMEN_VISITOR, S.OMEN_VISITOR_KORANTHA)
  L.expect(not present() and not L.getFlag(S.FLAG_OMEN_KORANTHA), "a new visitor does not spawn on top of the player")
  L.go(16, 35)
  L.wait(30)
  local x, y = L.pos()
  L.expect(x ~= 17 or y ~= 35, "the player actually vacates the visitor's tile")
  L.waitUntil(present, 600, "the visitor after the player leaves its tile")
  L.expect(present(), "the pending visitor arrives after its tile is free")
  L.shot("visitor_tile_freed")
  nextDay(S.OMEN_GOOD_SIGN, S.OMEN_SIGN_BLESSING)
  L.runHeader("RolloverTest_IsthmusHeader")
  L.expect(L.mapId() == S.MAP_ISTHMUS, "the actual Isthmus hill spur")
  nextDay(S.OMEN_VISITOR, S.OMEN_VISITOR_NEMECUB)
  L.expect(L.objectAt(S.LOCALID_NEMECUB) ~= nil and not L.getFlag(S.FLAG_OMEN_NEMECUB),
           "Nemecub arrives on its new day without Isthmus reentry")
  L.shot("nemecub_arrived")
  nextDay(S.OMEN_GOOD_SIGN, S.OMEN_SIGN_BLESSING)
  L.expect(L.objectAt(S.LOCALID_NEMECUB) == nil and L.getFlag(S.FLAG_OMEN_NEMECUB),
           "Nemecub expires on-map without an interaction")
end)
