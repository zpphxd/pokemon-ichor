def _nets_art():
    """A fishing net hung from two pegs: head rope with cork floats, a
    diamond mesh sagging between them, a weighted foot rope."""
    import math
    W, H = 32, 32
    g = [["."] * W for _ in range(H)]
    left, right, top = 4, 27, 8
    for x in range(left, right + 1):
        t = (x - left) / (right - left)
        bottom = int(round(top + 6 + 12 * math.sin(math.pi * t)))
        for y in range(top + 1, bottom):
            if (x + y) % 4 == 0 or (x - y) % 4 == 0:
                g[y][x] = "j" if (x + y) % 8 else "K"
        g[bottom][x] = "K"
        if x % 3 == 1:
            g[bottom + 1][x] = "S"     # lead sinkers on the foot rope
    for x in range(left - 1, right + 2):
        g[top][x] = "K"                 # head rope
    for x in range(left + 1, right, 4):  # cork floats
        g[top - 1][x] = "k"
        g[top - 1][x + 1] = "k"
        g[top][x] = "J"
        g[top][x + 1] = "j"
        g[top + 1][x] = "j"
        g[top + 1][x + 1] = "K"
    for px in (left - 1, right + 1):     # pegs
        g[top - 2][px] = "k"
        g[top - 1][px] = "K"
        g[top][px] = "k"
    # a dried starfish caught in the mesh
    for (dx, dy, c) in [(0, 0, "m"), (-1, 0, "m"), (1, 0, "m"), (0, -1, "m"), (0, 1, "d"),
                        (-2, 1, "d"), (2, 1, "d"), (0, -2, "m")]:
        g[17 + dy][19 + dx] = c
    return "\n".join("".join(r) for r in g)


