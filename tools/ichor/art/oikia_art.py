# --------------------------------------------------------------------------
# Stamps. Each is drawn in one palette, a whole number of metatiles in size.
# `top` art (optional) goes on the top layer, drawn over the player.
# `flatten` composites the art into the bottom layer (allowed only when the
# stamp shares the base's palette), which frees the top layer.
# --------------------------------------------------------------------------

STAMPS = {}


def stamp(name, pal, art, w, h, top=None, walk=(), behavior=None, flatten=False, note=""):
    """w, h in metatiles. walk: cells (cx, cy) the player may stand on.
    behavior: {(cx, cy): 'MB_...'}."""
    img = grid(pal, art, w * 16, h * 16)
    STAMPS[name] = {
        "pal": pal,
        "img": img,
        "top": grid(pal, top, w * 16, h * 16) if top else None,
        "w": w,
        "h": h,
        "walk": set(walk),
        "behavior": dict(behavior or {}),
        "flatten": flatten,
        "note": note,
    }


