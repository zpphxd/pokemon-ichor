"""Pixel art for the oikia tileset: the furnishings of an ancient Greek house.

Everything here is drawn by hand as character grids. Each grid uses one of the
seven oikia palettes below, and every palette is built from colors that appear
in no aethos palette, so Porytiles can only place these tiles in palettes 6-12.
That keeps oikia independent of the primary it is paired with.

Pieces:
  FLOORS   16x16 bottom-layer floors (terracotta tiles, wooden boards,
           limestone flags), with shadowed variants made by shade maps.
  WALLS    16x32 back-wall strips (beam, rafter ends, plaster, painted dado).
  RUGS     woven rugs, drawn as 9-slices on the bottom layer.
  STAMPS   furniture and objects, drawn on the middle (and sometimes top)
           layer over a floor or wall, each a whole number of metatiles.

oikia_build.py assembles these into metatiles; oikia_rooms.py lays out rooms.
"""
