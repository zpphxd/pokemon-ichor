# --------------------------------------------------------------------------
# Walls (16x32: rows 0 and 1 of a room). A dark ceiling beam with rafter
# ends, whitewashed plaster, and a painted dado with a Greek key.
# --------------------------------------------------------------------------

KEY8 = [  # one period of a running spiral key, 8x8; '#' is the line
    "#######.",
    "#.....#.",
    "#.###.#.",
    "#.#.#.#.",
    "#.#...#.",
    "#.#####.",
    "#.......",
    "########",
]


def wall_strip(dado="R", dado_lit="r", dado_dark="D", key="o"):
    rows = []
    rows.append("k" * 16)                       # 0 ceiling edge
    rows.append("2" * 16)                       # 1 beam
    rows.append("3" * 16)                       # 2 beam, lit
    rows.append("2" * 16)                       # 3
    rows.append("1" * 16)                       # 4 beam underside
    rows.append("s23321sss23321ss"[:16])        # 5 rafter ends
    rows.append("s12211sss12211ss"[:16])        # 6
    rows.append("ps1111spps1111sp"[:16])        # 7 shadow under rafters
    rows.append("pppssssppppssssp"[:16])        # 8
    for y in range(9, 21):
        rows.append("p" * 16)                   # 9-20 plaster
    rows.append("s" * 16)                       # 21 shade line
    rows.append(key * 16)                       # 22 painted line
    for y in range(8):                          # 23-30 dado with key
        rows.append("".join(key if c == "#" else dado for c in KEY8[y] * 2))
    rows.append(dado_dark * 16)                 # 31
    # plaster texture: a few lit and shaded flecks
    rows = [list(r) for r in rows]
    for (x, y, c) in [(3, 11, "w"), (10, 13, "w"), (13, 17, "s"), (6, 18, "w"), (1, 16, "s"), (12, 10, "w")]:
        rows[y][x] = c
    return grid("wall", "\n".join("".join(r) for r in rows))


