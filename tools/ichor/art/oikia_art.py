# The one place a color is allowed to repeat across palettes is INK; any other
# repeats are fine too (each palette is separate in VRAM), but no oikia color
# may equal an aethos color. oikia_build.py checks that.


def grid(pal, text, w=None, h=None):
    """Parse a character grid into an (h, w, 4) RGBA array ('.' = clear)."""
    rows = [r for r in text.strip("\n").split("\n")]
    rows = [r.rstrip() for r in rows]
    w = w or max(len(r) for r in rows)
    h = h or len(rows)
    assert len(rows) <= h, f"{len(rows)} rows > {h}"
    out = np.zeros((h, w, 4), np.uint8)
    colors = PALETTES[pal]
    for y, row in enumerate(rows):
        assert len(row) <= w, f"row {y} is {len(row)} wide > {w}: {row!r}"
        for x, ch in enumerate(row):
            if ch in ". ":
                continue
            if ch not in colors:
                raise ValueError(f"{pal}: unknown char {ch!r} at ({x},{y}) in {row!r}")
            out[y, x, :3] = colors[ch]
            out[y, x, 3] = 255
    return out


def recolor(img, pal, mapping):
    """Swap colors by character: mapping {'a': 'b'} turns color a into b."""
    colors = PALETTES[pal]
    out = img.copy()
    src = img[..., :3]
    for a, b in mapping.items():
        m = (src == colors[a]).all(-1) & (img[..., 3] > 0)
        out[m, :3] = colors[b]
    return out


def hflip(img):
    return img[:, ::-1].copy()


