def _stairs_up_art():
    """Whitewashed masonry stairs climbing west along the back wall, up
    through a hatch in the ceiling. 32x48: rows 0-2 of a room."""
    W, H = 32, 48
    g = [["."] * W for _ in range(H)]
    # the hatch in the ceiling above the top steps
    for y in range(0, 16):
        for x in range(0, 15):
            g[y][x] = "k"
    for x in range(0, 15):
        g[15][x] = "1"
    for y in range(0, 16):
        g[y][14] = "2" if y > 0 else "k"
        g[y][15] = "k"
    for y in range(1, 15):
        g[y][13] = "1"
    for i in range(8):
        x0, x1 = 28 - 4 * i, 31 - 4 * i
        top = 44 - 4 * i
        for x in range(x0, x1 + 1):
            g[top - 1][x] = "k"
            g[top][x] = "w"
            g[top + 1][x] = "w" if x < x1 else "p"
            g[top + 2][x] = "s"
            for y in range(top + 3, H):
                g[y][x] = "p"
        # riser outline on the step's right edge, up from the step below
        if i > 0:
            for y in range(top - 1, top + 4):
                g[y][x1] = "k"
            g[top + 3][x1] = "s"
    # lower courses in shade, and the stair's bottom edge
    for x in range(W):
        for y in range(40, H):
            if g[y][x] == "p" and y >= 44:
                g[y][x] = "s"
        g[H - 1][x] = "S" if g[H - 1][x] != "." else "."
    # left end of the masonry
    for y in range(16, H):
        if g[y][0] != ".":
            g[y][0] = "k" if y > 16 else g[y][0]
    return "\n".join("".join(r) for r in g)


