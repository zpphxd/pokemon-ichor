def _square(hi, mid, lo, speck=None):
    """One 8x8 fired-clay tile: lit top-left bevel, low bottom-right, grout."""
    rows = []
    for y in range(8):
        row = ""
        for x in range(8):
            if x == 7 or y == 7:
                row += "g"
            elif y == 6 or x == 6:
                row += lo
            elif y == 0 or x == 0:
                row += hi
            else:
                row += mid
        rows.append(row)
    if speck:
        for (x, y, c) in speck:
            rows[y] = rows[y][:x] + c + rows[y][x + 1:]
    return rows


def _join(a, b):
    return [ra + rb for ra, rb in zip(a, b)]


def floor_terracotta_small():
    a = _square("T", "t", "x", [(3, 2, "x"), (2, 4, "T")])
    b = _square("t", "x", "u", [(4, 3, "u"), (2, 2, "t")])
    rows = _join(a, b) + _join(b, a)
    return grid("floor", "\n".join(rows))


def _bigtile(hi, mid, lo, specks=()):
    """One 16x16 fired-clay paver: lit top-left edge, low bottom-right, grout."""
    rows = []
    for y in range(16):
        row = ""
        for x in range(16):
            if x == 15 or y == 15:
                row += "g"
            elif x == 14 or y == 14:
                row += lo
            elif x == 0 or y == 0:
                row += hi
            else:
                row += mid
        rows.append(row)
    rows = [list(r) for r in rows]
    for (x, y, c) in specks:
        rows[y][x] = c
    return grid("floor", "\n".join("".join(r) for r in rows))


def floor_terracotta():
    return _bigtile("T", "t", "x", [(4, 5, "x"), (5, 5, "x"), (10, 9, "T"), (9, 11, "x"), (3, 11, "T")])


def floor_terracotta_alt():
    return _bigtile("t", "x", "u", [(6, 4, "u"), (11, 10, "t"), (12, 10, "t"), (4, 12, "u")])


def floor_boards():
    # Wide boards running north-south (the upper storey is laid on beams),
    # butt joints staggered, a little grain.
    p0 = ["jmmmmmmm"] * 16
    p1 = ["jmmmmmmm"] * 16
    p0[5] = "jjjjjjjj"
    p0[6] = "jWWWWWWm"
    p1[13] = "jjjjjjjj"
    p1[14] = "jWWWWWWm"
    for (x, y) in [(3, 9), (3, 10), (4, 11), (5, 1), (5, 2), (6, 14)]:
        p0[y] = p0[y][:x] + "n" + p0[y][x + 1:]
    for (x, y) in [(4, 3), (4, 4), (3, 5), (6, 8), (6, 9), (2, 11)]:
        p1[y] = p1[y][:x] + "n" + p1[y][x + 1:]
    rows = _join(p0, p1)
    return grid("floor", "\n".join(rows))


def floor_flags():
    # Long limestone flags in running bond (16x8 stones, offset by 8).
    rows = []
    for y in range(16):
        row = ""
        for x in range(16):
            band = y // 8
            yy = y % 8
            # seam positions: band 0 seam at x=15, band 1 seam at x=7
            sx = 15 if band == 0 else 7
            xx = (x - sx - 1) % 16  # distance from the seam on its left
            if yy == 7 or x == sx:
                row += "Q"
            elif yy == 6 or xx == 15 - 1 + 0 and False:
                row += "q"
            elif yy == 0 or xx == 0:
                row += "L"
            else:
                # second tone on the right-hand stone of band 1
                if band == 1 and x > 7:
                    row += "y"
                else:
                    row += "l"
        rows.append(row)
    # low edge on each stone's right side
    rows = [list(r) for r in rows]
    for y in range(16):
        sx = 15 if y // 8 == 0 else 7
        x = (sx - 1) % 16
        if y % 8 != 7:
            rows[y][x] = "q"
    for (x, y) in [(4, 3), (5, 3), (11, 2), (2, 11), (12, 12), (13, 12), (9, 10)]:
        if rows[y][x] in "ly":
            rows[y][x] = "q"
    rows = ["".join(r) for r in rows]
    return grid("floor", "\n".join(rows))


FLOOR_SHADE = {
    "terracotta": {"T": "x", "t": "u", "x": "u", "u": "v", "v": "g"},
    "boards": {"W": "m", "m": "n", "n": "j"},
    "flags": {"L": "y", "l": "q", "y": "q", "q": "Q"},
}


def shade(img, material, mask):
    """Darken img where mask (h,w bool) is set, one step down the ramp."""
    m = FLOOR_SHADE[material]
    dark = recolor(img, "floor", m)
    out = img.copy()
    out[mask] = dark[mask]
    return out


def floor_variants(material, base, alt=None):
    """plain (and an alternate plain for empty floor), top shadow (under the
    back wall), left shadow, and the corner where they meet."""
    yy, xx = np.mgrid[0:16, 0:16]
    top = (yy < 4) | ((yy == 4) & (xx % 2 == 0))
    left = (xx < 3) | ((xx == 3) & (yy % 2 == 0))
    out = {
        "plain": base,
        "top": shade(base, material, top),
        "left": shade(base, material, left),
        "corner": shade(base, material, top | left),
    }
    if alt is not None:
        out["alt"] = alt
    return out


