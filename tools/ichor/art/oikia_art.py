# Rugs: 9-slices on the bottom layer. Each is a 48x48 grid; the builder
# cuts the corners, edges and center out of it.
# --------------------------------------------------------------------------


def rug_red():
    # Madder field with a saffron Greek-key border and small rosettes.
    g = [["r"] * 48 for _ in range(48)]
    def put(x, y, c):
        if 0 <= x < 48 and 0 <= y < 48:
            g[y][x] = c
    for i in range(48):
        for d in (0, 47):
            put(i, d, "R"); put(d, i, "R")
        for d in (1, 46):
            put(i, d, "o"); put(d, i, "o")
    # border band rows/cols 2..9 dark ground with key in ochre
    for y in range(2, 46):
        for x in range(2, 46):
            inner = 10 <= x < 38 and 10 <= y < 38
            if not (10 <= x <= 37 and 10 <= y <= 37):
                g[y][x] = "R"
    # key on top/bottom bands (horizontal), period 8 aligned to 16
    for x in range(2, 46):
        for yy in range(8):
            if KEY8[yy][(x - 2) % 8] == "#":
                put(x, 2 + yy, "o")
                put(x, 45 - yy, "o")
    for y in range(10, 38):
        for xx in range(8):
            if KEY8[xx][(y - 10) % 8] == "#":
                put(2 + xx, y, "o")
                put(45 - xx, y, "o")
    # inner line
    for i in range(10, 38):
        put(i, 10, "y"); put(i, 37, "y"); put(10, i, "y"); put(37, i, "y")
    # field rosettes at the 16px centers
    for cy in (16, 32):
        for cx in (16, 32):
            for (dx, dy, c) in [(0, -1, "y"), (-1, 0, "y"), (1, 0, "y"), (0, 1, "y"), (0, 0, "o"),
                                (-1, -1, "R"), (1, -1, "R"), (-1, 1, "R"), (1, 1, "R")]:
                put(cx + dx - 8 + 8, cy + dy, c)
    return grid("cloth", "\n".join("".join(r) for r in g))


def rug_blue():
    # Indigo field with an undyed wave-scroll ("running dog") border.
    g = [["u"] * 48 for _ in range(48)]
    def put(x, y, c):
        if 0 <= x < 48 and 0 <= y < 48:
            g[y][x] = c
    for y in range(48):
        for x in range(48):
            if not (9 <= x <= 38 and 9 <= y <= 38):
                g[y][x] = "i"
    for i in range(48):
        for d in (0, 47):
            put(i, d, "k"); put(d, i, "k")
        for d in (1, 46):
            put(i, d, "c"); put(d, i, "c")
        for d in (8, 39):
            if 8 <= i <= 39:
                put(i, d, "c"); put(d, i, "c")
    WAVE = [  # 8-wide wave scroll, 5 tall
        "..cc....",
        ".c..c...",
        ".c.cc...",
        "c...c...",
        "cccccccc",
    ]
    for x in range(2, 46):
        for yy in range(5):
            if WAVE[yy][(x - 2) % 8] == "c":
                put(x, 2 + yy, "c")
                put(x, 45 - yy, "c")
    for y in range(9, 39):
        for xx in range(5):
            if WAVE[xx][(y - 9) % 8] == "c":
                put(2 + xx, y, "c")
                put(45 - xx, y, "c")
    # field: a lattice of small lit diamonds
    for y in range(10, 38):
        for x in range(10, 38):
            if (x + y) % 8 == 0 and (x - y) % 8 == 0:
                put(x, y, "U")
                put(x - 1, y, "U"); put(x + 1, y, "U"); put(x, y - 1, "U"); put(x, y + 1, "U")
    return grid("cloth", "\n".join("".join(r) for r in g))


