#!/usr/bin/env python3
"""Draw, slice, compile and catalog gTileset_Loom: the Loom and the Stair of Hours.

1. Paints every scene of both maps (loom_art.all_scenes()) and slices them into
   distinct 16x16 cells, one metatile each (loom_art.slice_scenes()). Each 8x8
   tile of each layer must draw from one palette group; tiles within
   NEAR_DUPLICATE_PX of another are redrawn as that one.
2. Writes data/tilesets/secondary/loom/porytiles_src and compiles it with
   Porytiles against an empty stand-in primary (as the Labyrinth is), so it uses
   only its own tiles and palettes 6-12 and pairs with the oikos primary.
3. Writes tools/ichor/maps/loom_tiles.py: every scene as a grid of metatile ids,
   with its walk codes, for the map builder (tools/ichor/maps/climax.py) and the
   setmetatile lists the scripts swap; the sheet and scene previews in
   design/phase4/img/; and design/phase4/TILES_loom.md.

Usage: /usr/bin/python3 tools/ichor/art/loom_build.py [--no-compile]
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import emporion_build as EB  # noqa: E402
import emporion_lib as E  # noqa: E402
import loom_art as A  # noqa: E402
from kalliste_lib import write_sources  # noqa: E402

ROOT = A.K.ROOT
IMG = ROOT / "design/phase4/img"


SETS = {
    # dir: (symbol, scene builder, the palette groups it uses)
    "loom": ("gTileset_Loom", A.loom_scenes, ("rock", "loom", "warp", "chain", "stone", "sky")),
    "stair_of_hours": ("gTileset_StairOfHours", A.stair_scenes, ("stone", "sky")),
}


class Spec:
    art = A
    temple = True

    def __init__(self, name):
        self.name = self.dir = name
        self.symbol, self.scenes, groups = SETS[name]
        self.groups = {g: A.GROUPS[g] for g in groups}
        self.src = ROOT / f"data/tilesets/secondary/{self.dir}/porytiles_src"
        self.bin = ROOT / f"data/tilesets/secondary/{self.dir}/porytiles_bin"
        self.cfg = ROOT / f"porytiles/tilesets/{self.symbol}"
        self.scratch = ROOT / f"build/{self.dir}_porytiles"
        self.out = ROOT / f"build/{self.dir}"
        self.sheet = IMG / f"{self.dir}_sheet.png"
        self.pieces = IMG / f"{self.dir}_pieces.png"


def compile_tileset(spec):
    if spec.symbol not in (ROOT / "src/data/tilesets/headers.h").read_text():
        for f in ("tileset-manifest.json", "tileset.cache.json"):
            (spec.cfg / f).unlink(missing_ok=True)
    sec = EB.scratch_project(spec)
    r = EB.run([EB.porytiles(), "compile-tileset", "-C", spec.scratch, "--no-verify-checksums",
                spec.symbol])
    if r.stdout.strip() or r.stderr.strip():
        print((r.stdout + r.stderr)[-2000:])
    if spec.bin.exists():
        shutil.rmtree(spec.bin)
    shutil.copytree(sec / "porytiles_bin", spec.bin)
    spec.cfg.mkdir(parents=True, exist_ok=True)
    for f in ("tileset-manifest.json", "tileset.cache.json"):
        p = spec.scratch / f"porytiles/tilesets/{spec.symbol}/{f}"
        if p.exists():
            shutil.copy2(p, spec.cfg / f)
    (spec.cfg / "config.yaml").write_text(
        "# Written by tools/ichor/art/loom_build.py; edit it there.\n"
        "tileset:\n  primary_pairing:\n    mode: manual\n    partners: [gTileset_Oikos]\n"
        + EB.hints_yaml(spec.groups, E.C))


def scene_png(sc, path, scale=1):
    comp = np.zeros((sc.h * 16, sc.w * 16, 3), np.uint8)
    comp[:] = (255, 0, 255)
    for L in (sc.B, sc.M):
        m = L.a[..., 3] > 0
        comp[m] = L.a[..., :3][m]
    Image.fromarray(comp).resize((sc.w * 16 * scale, sc.h * 16 * scale), Image.NEAREST).save(path)


def write_catalog(spec, structs, grids, scenes):
    ids = {i: s.ids[0][0] for i, s in enumerate(structs)}
    out = {}
    for sc in scenes:
        g = grids[sc.name]
        out[sc.name] = {
            "w": sc.w, "h": sc.h,
            "ids": [[ids[i] for i in row] for row in g],
            "walk": ["".join(r) for r in sc.walk],
        }
    p = ROOT / f"tools/ichor/maps/{spec.dir}_tiles.py"
    p.write_text(f'"""Metatile grids of {spec.symbol}\'s scenes. Generated by '
                 'tools/ichor/art/loom_build.py; do not edit.\n\n'
                 'SCENES[name] = {"w", "h", "ids": rows of metatile ids, "walk": rows of "." / "X"}.\n"""\n\n'
                 f"SYMBOL = {spec.symbol!r}\n"
                 "SCENES = " + json.dumps(out, separators=(",", ":")) + "\n")
    return out


