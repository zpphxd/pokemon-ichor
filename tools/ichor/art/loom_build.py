def build(name, compile_=True):
    spec = Spec(name)
    scenes = spec.scenes()
    IMG.mkdir(parents=True, exist_ok=True)
    for sc in scenes:
        scene_png(sc, IMG / f"loom_scene_{sc.name}.png", 1)
    structs, grids = A.slice_scenes(scenes)
    probs = A.validate(structs)
    if not probs:
        before = len(EB._tiles(structs))
        merges = EB.merge_near_duplicates(structs)
        print(f"{name}: merged {len(merges)} near-duplicate tiles: {before} -> {len(EB._tiles(structs))}")
        probs = A.validate(structs)
    for p in probs[:40]:
        print("PROBLEM:", p)
    if probs:
        sys.exit(f"{len(probs)} problems")
    rows = A.pack(structs)
    print(f"{name}: {len(structs)} metatiles, {rows} sheet rows")
    write_sources(structs, rows, spec.src)
    write_catalog(spec, structs, grids, scenes)
    if not compile_:
        return None
    compile_tileset(spec)
    used = EB.verify(spec, rows, {})
    print("colors per palette 6-12:", EB.palette_report(spec))
    EB.run([sys.executable, ROOT / "tools/ichor/render_map.py", "--sheet", f"data/tilesets/secondary/{spec.dir}",
            "--primary", "oikos", "--scale", "2", "-o", spec.sheet])
    return structs, scenes, used


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-compile", action="store_true")
    ap.add_argument("sets", nargs="*", default=list(SETS))
    args = ap.parse_args()
    done = {}
    for name in args.sets:
        done[name] = build(name, not args.no_compile)
    if all(done.get(n) for n in SETS):
        write_doc(done)


if __name__ == "__main__":
    main()
