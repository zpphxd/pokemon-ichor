"""The polish pass's pieces for Thyrsa's sparse rooms (Act II batch 2): Manto's house,
where birdcages hang from every beam, and Polos's narrow house. Registered into
thyrsa_rooms_art.STAMPS on import, like the batch 1 modules."""
from thyrsa_rooms_art import stamp
import thyrsa_rooms_homes as H


def _canvas(w, h):
    return [["."] * w for _ in range(h)]


def _text(g):
    return "\n".join("".join(r) for r in g)


def _paste(g, art, ox, oy):
    for dy, row in enumerate(art):
        for dx, c in enumerate(row):
            if c != "." and 0 <= oy + dy < len(g) and 0 <= ox + dx < len(g[0]):
                g[oy + dy][ox + dx] = c


# ---- Manto: cages from every beam -------------------------------------------

def _beam_cage(bird, drop):
    """A birdcage hung on a cord from the wall's top beam, 1x2 cells, in front of the
    plaster: the cord drops `drop` px before the cage, so a row of them hang at
    different heights."""
    g = _canvas(16, 32)
    cage = H._cage(bird).split("\n")
    top = 2 + drop
    for y in range(3, top + 2):
        g[y][7] = "K"
        g[y][8] = "k"
    # the hook on the beam
    _paste(g, [".kk.", "kJJk"], 6, 2)
    _paste(g, cage, 0, top)
    return _text(g)


