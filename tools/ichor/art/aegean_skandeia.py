_CURLS = [
    [".hh.", "h..l", "l.m.", ".mm."],
    [".hhl", "h...", "h.lm", ".lm."],
    ["hhl.", "..lm", ".hm.", "hm.."],
    [".hl.", "h.hl", "l.m.", "lm.."],
]


def _shavings(seed, n):
    """Pale curls of planed wood, a heap of them, each with a dark inside."""
    rnd = np.random.RandomState(seed)
    c = Canvas(16, 16)
    spots = [(1, 1), (6, 0), (11, 2), (3, 6), (9, 6), (0, 11), (6, 11), (12, 10), (7, 4), (2, 3)]
    rnd.shuffle(spots)
    for (x, y) in spots[:n]:
        curl = _CURLS[rnd.randint(len(_CURLS))]
        c.paste(curl, x + rnd.randint(0, 2), y + rnd.randint(0, 2))
        c.px(x + 2, y + 2, "d")
    return c


for _i, (_n, _k) in enumerate((("shavings", 9), ("shavings_b", 7), ("shavings_c", 4))):
    stamp(_n, "wood", _shavings(_i + 3, _k), 1, 1, walk={(0, 0)},
          note="curls of wood shavings, ankle-deep (walkable)")

