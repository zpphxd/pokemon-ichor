def _keel():
    """A half-built keel on two trestles: the keel timber, the stem post
    curving up at the bow, and three frames standing on the after part."""
    c = Canvas(64, 32)
    # trestles
    for x0 in (10, 46):
        c.paste("""
..kk....kk..
.kmlk..kmlk.
.kmlk..kmlk.
kkkkkkkkkkkk
khhhhhhhhhhk
kmmmmmmmmmmk
kkkkkkkkkkkk
.kmk....kmk.
kmdk....kmdk
kmk......kmk
kkk......kkk""", x0, 21)
    # the keel timber
    c.rect(4, 17, 61, 21, "k")
    c.hline(5, 60, 18, "h")
    c.hline(5, 60, 19, "l")
    c.hline(5, 60, 20, "m")
    # the stem post curving up at the left
    pts = [(5, 17), (4, 15), (3, 13), (3, 11), (3, 9), (4, 7), (5, 5), (7, 3), (9, 2)]
    for (x, y) in pts:
        c.rect(x, y, x + 2, y + 2, "l")
    for (x, y) in pts:
        c.px(x, y, "h")
        c.px(x + 2, y + 2, "m")
    c.px(10, 2, "d")
    # frames (ribs), seen from the side: each rises from the keel and bows
    # outward toward the gunwale, lower toward the stern
    bow = [0, 0, 0, 0, 1, 1, 1, 2, 2, 2, 3, 3, 4]
    for i, x in enumerate((20, 28, 36, 44, 52)):
        top = 4 + i
        for y in range(top, 17):
            dx = bow[min(16 - y, len(bow) - 1)]
            c.px(x - dx, y, "h")
            c.px(x - dx + 1, y, "l")
            c.px(x - dx + 2, y, "m")
        c.px(x - bow[min(16 - top, len(bow) - 1)] + 1, top - 1, "h")
    # the first strakes pinned along the frames
    for (y, x0, x1) in ((9, 16, 54), (13, 12, 58)):
        c.hline(x0, x1, y, "h")
        c.hline(x0, x1, y + 1, "m")
        for x in range(x0 + 4, x1, 8):
            c.px(x, y, "y")
    c.outline()
    return c


