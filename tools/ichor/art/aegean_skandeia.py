def _sponges(seed, n=3):
    """Sponges on short cords from the beam: lumpy golden cushions, lit on
    top, pitted with dark pores."""
    rnd = np.random.RandomState(seed)
    c = Canvas(16, 32)
    spots = [(3, 13, 3.4, 3.0), (11, 10, 3.6, 3.2), (7, 20, 4.2, 3.4)][:n] if n == 3 else \
        [(4, 12, 4.0, 3.4), (11, 18, 4.4, 3.6)]
    for (x, cy, rx, ry) in spots:
        c.vline(x, 7, int(cy - ry), "n")

        def sh(px, py, nx, ny):
            v = -0.5 * nx - 0.9 * ny + rnd.rand() * 0.25
            return "J" if v > 0.35 else "j" if v > -0.45 else "K"
        inside = c.ellipse(x, cy, rx, ry, shade=sh)
        # lumps on the rim
        for (dx, dy) in [(-3, -1), (3, 0), (-1, 3), (2, -3)]:
            c.px(int(x + dx * rx / 3.4), int(cy + dy * ry / 3.0), "j")
        for (px, py) in inside:
            if (px * 5 + py * 3 + seed) % 7 == 0 and c.get(px, py) != "J":
                c.px(px, py, "K")
            elif (px * 3 + py * 7 + seed) % 11 == 0:
                c.px(px, py, "K")
    c.paste("kk", 0, 6)
    c.outline()
    return c


