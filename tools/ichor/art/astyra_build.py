#!/usr/bin/env python3
"""Draw, compile, register and catalog gTileset_Astyra and gTileset_Akropolis.

The awe pass, items 1 and 2 (design/AWE_PASS.md):

  astyra     the capital: the Akropolis rock as its skyline with the Parthenon
             and Promachos's spear over it, the agora and its stoas, the
             Library, the Asclepeion, courtyard houses, the walls and the
             Dipylon gate, the fountain house, the harbor's quays and sheds
  akropolis  the rock's top: the switchback ramp, the Propylaia, Athena
             Promachos (4 x 9), the Parthenon (14 x 8), the Erechtheion and its
             maidens, the Old Temple's ruins

Both pair with the aethos primary and borrow its grass, path, sand and sea.
The art is tools/ichor/art/astyra_art.py (city: astyra_city_art.py), every
column from the shared column kit tools/ichor/art/columns.py. The pipeline
is kythera_build.py's (packing, the Porytiles scratch project, borrowed
ground, verification, registration); this file gives it the two specs and
writes tools/ichor/maps/astyra_tiles.py (the catalogs as Python dicts, for
the map builders) and design/awe/TILES_<name>.md.

Usage: /usr/bin/python3 tools/ichor/art/astyra_build.py [astyra|akropolis|all] [--no-compile]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kythera_build as KB  # noqa: E402
import kythera_lib as K  # noqa: E402
import lakonia_build as LB  # noqa: E402
import astyra_art as AA  # noqa: E402

ROOT = K.ROOT
TILES_PY = ROOT / "tools/ichor/maps/astyra_tiles.py"
DOC = ROOT / "design/awe"
NAMES = ["astyra", "akropolis"]
# pieces whose every pixel was placed by hand: never redrawn as a near-duplicate
EXACT = {"promachos", "skyline_promachos", "kodros", "kairos", "votive", "brazier"}

KB.ANIM_ORDER.update({
    # the spear tip: a long rest, the sparkle running down it, the flare
    "glint": ["0", "0", "0", "0", "0", "0", "1", "2", "3", "0", "0", "0"],
    "spout": ["0", "1", "2"],
    # a brazier's fire, never still
    "flame": ["0", "1", "2"],
})


def spec(name):
    if name == "akropolis":
        by = AA.akropolis_structures()
        groups = {g: AA.GROUPS[g] for g in ("marble", "bronze", "ruin", "rock", "green")}
        return {
            "symbol": "gTileset_Akropolis", "dir": "akropolis", "label": "Akropolis",
            "title": "the Akropolis of Astyra", "maps": "Astyra_Akropolis", "groups": groups,
            # the architecture's flat fields merge at 8 px (statues are EXACT)
            "merge_px": 8,
            # one section, tallest first, so the packer leaves few holes in
            # the 512 metatiles (the polish pass added the precinct kit)
            "sections": [("akropolis", [by["parthenon"], by["promachos"], by["erechtheion"],
                                        by["propylaia"], by["old_columns"], by["cliff"],
                                        by["foundations"], by["pave"], by["col_moss3"], by["ramp"],
                                        by["altar"], by["outcrop"], by["votive"], by["brazier"],
                                        by["edge"], by["spring"], by["ruins"]])],
            "labels": [("spring", [("well_shut", "WellShut"), ("well_open", "WellOpen"),
                                   ("cleft", "Cleft"), ("rubble", "Rubble")])],
        }
    if name == "astyra":
        import astyra_city_art as CA
        by = CA.city_structures()
        groups = {g: AA.GROUPS[g] for g in ("marble", "bronze", "ruin", "rock", "roof", "green", "water")}
        return {
            "symbol": "gTileset_Astyra", "dir": "astyra", "label": "Astyra",
            "title": "Astyra, the capital", "maps": "Astyra, Astyra_Harbor", "groups": groups,
            "merge_px": 6,             # statues are EXACT; the new Promachos crop needed the room
            "sections": CA.sections(by),
            "labels": CA.LABELS,
        }
    raise SystemExit(f"astyra_build: unknown tileset {name}")


def write_tiles_py(name, cat):
    cur = {}
    if TILES_PY.exists():
        ns = {}
        exec(compile(TILES_PY.read_text(), str(TILES_PY), "exec"), ns)
        cur = ns.get("TILESETS", {})
    slim = {"symbol": cat["tileset"], "structures": {}, "fronts": {}}
    for d in cat["structures"]:
        slim["structures"][d["key"]] = {
            "w": d["w"], "h": d["h"], "ids": d["ids"], "walk": d["walk"],
            "names": {k: tuple(v) for k, v in d["names"].items()},
            "ground": d["ground"], "section": d["section"],
        }
    cur[name] = slim
    body = json.dumps(cur, indent=1, sort_keys=True)
    body = body.replace("true", "True").replace("false", "False").replace("null", "None")
    TILES_PY.write_text(
        '"""Metatile ids of gTileset_Astyra and gTileset_Akropolis, for map builders.\n\n'
        "Generated by tools/ichor/art/astyra_build.py; do not edit. One entry per\n"
        "tileset, each {'symbol', 'structures': {key: {'w', 'h', 'ids', 'walk',\n"
        "'names' {piece: (x, y)}, 'ground', 'section'}}, 'fronts': {}} in the same\n"
        "shape as kythera_tiles.py, so kythera_maps.Map can place them. The catalogs\n"
        "are design/awe/TILES_astyra.md and TILES_akropolis.md.\n"
        '"""\n\n'
        f"TILESETS = {body}\n\n\n"
        "def mid(tileset, key, name=None, x=0, y=0):\n"
        "    s = TILESETS[tileset]['structures'][key]\n"
        "    if name is not None:\n"
        "        x, y = s['names'][name]\n"
        "    return s['ids'][y][x]\n")


def catalog_md(name, sp, structs, n_tiles, n_meta):
    DOC.mkdir(parents=True, exist_ok=True)
    out = [f"# {name} tileset catalog\n",
           f"`{sp['symbol']}` is {sp['title']}. It serves {sp['maps']}, paired with the "
           "`aethos` primary (open grass, paths, sand, sea, olives, cypresses, stelai, herms).\n",
           f"**Generated** by `tools/ichor/art/astyra_build.py {name}`; the art is "
           "`tools/ichor/art/astyra_art.py` and `astyra_city_art.py`, every column from the shared "
           "kit `tools/ichor/art/columns.py` (STYLE.md, \"Architecture: Gen 3 craft and Greek forms\").\n",
           f"**Budget:** {n_tiles} of 504 tiles, {n_meta} metatiles. Palettes (secondary slots "
           f"6-12): {', '.join(sp['groups'])}.\n",
           f"Images: `design/phase4/img/{sp['dir']}_pieces.png` (every piece on its ground) and "
           f"`design/phase4/img/{sp['dir']}_sheet.png` (the numbered sheet).\n",
           "Walk codes: `X` solid, `.` walkable, `T` walkable and drawn over the player.\n"]
    for sec, ss in sp["sections"]:
        out.append(f"\n## {sec}\n")
        for s in ss:
            out.append(f"### `{s.key}` ({s.w} x {s.h}): {s.title}\n")
            if s.notes:
                out.append(s.notes + "\n")
            if s.w * s.h <= 24 and s.names:
                items = ", ".join(f"`{n}` 0x{s.ids[y][x]:03X}" for n, (x, y) in s.names.items())
                out.append(items + "\n")
            else:
                out.append(f"Top-left id 0x{s.ids[0][0]:03X}; cells by `r<row>c<col>` or position.\n")
    (DOC / f"TILES_{name}.md").write_text("\n".join(out))


def build_one(name, compile_=True):
    sp = spec(name)
    groups = sp["groups"]
    group_rgb = {g: {K.C[n] for n in names} for g, names in groups.items()}
    structs = [s for _, ss in sp["sections"] for s in ss]
    keys = [s.key for s in structs]
    assert len(keys) == len(set(keys)), f"duplicate structure keys in {name}"
    probs = K.validate(structs, group_rgb)
    if not probs:
        before = len(K.tiles_of(structs))
        merges = []
        # statues stay pixel-exact; the architecture's near-duplicates merge
        loose = [s for s in structs if s.key not in EXACT]
        for _ in range(2):
            merges += K.merge_near_duplicates(loose, sp.get("merge_px", KB.NEAR_DUPLICATE_PX), group_rgb)
        print(f"{name}: merged {len(merges)} near-duplicate tiles: {before} -> {len(K.tiles_of(structs))} tiles")
        probs = K.validate(structs, group_rgb)
    for p in probs[:60]:
        print("PROBLEM:", p)
    if probs:
        sys.exit(f"{len(probs)} problems")
    KB.fix_keys(structs)
    KB.check_anim_keys(structs)
    sp["rows"] = LB.auto_rows(sp)
    rows, used = KB.pack(sp)
    LB.write_sources(sp, structs, rows, used, filler="cm3")
    cat = KB.catalog(sp, structs)
    write_tiles_py(name, cat)
    LB.LABELS = KB.LABELS
    write_labels(sp, structs)
    print(f"{name}: {sum(s.w * s.h for s in structs)} metatiles in {rows} rows")
    if not compile_:
        return
    hdr = (ROOT / "src/data/tilesets/headers.h").read_text()
    cfg = ROOT / "porytiles/tilesets" / sp["symbol"]
    if f"const struct Tileset {sp['symbol']} =" not in hdr:
        for f in ("tileset-manifest.json", "tileset.cache.json"):
            (cfg / f).unlink(missing_ok=True)
    animated = KB.compile_tileset(sp, groups)
    patched = KB.borrow_ground(sp, structs)
    KB.register(sp, animated)
    _retitle(sp)
    n_tiles, n_meta = KB.verify(sp, rows, patched)
    KB.images(sp, structs)
    catalog_md(name, sp, structs, n_tiles, n_meta)


def write_labels(sp, structs):
    want = dict(sp.get("labels", []))
    if not want:
        return
    start = f"// {sp['symbol']} (Ichor: {sp['title']}), written by tools/ichor/art/astyra_build.py"
    end = f"// end {sp['symbol']}"
    lines = [start]
    by = {s.key: s for s in structs}
    for key, items in want.items():
        s = by[key]
        for nm, label in items:
            cx, cy = s.names[nm]
            lines.append(f"#define METATILE_{sp['label']}_{label:<24} 0x{s.ids[cy][cx]:03X}")
    lines.append(end)
    block = "\n".join(lines) + "\n"
    text = KB.LABELS.read_text()
    if start in text:
        a = text.index(start)
        b = text.index(end, a) + len(end) + 1
        text = text[:a] + block + text[b:]
    else:
        e = text.rindex("#endif")
        text = text[:e] + block + "\n" + text[e:]
    KB.LABELS.write_text(text)


def _retitle(sp):
    """kythera_build writes its own name into the registration comments."""
    for rel in ("src/data/tilesets/headers.h", "src/data/tilesets/graphics.h"):
        p = ROOT / rel
        t = p.read_text()
        t = t.replace(f"// Ichor: {sp['dir']}, {sp['title']} (Act III). Porytiles-managed, built by\n"
                      "// tools/ichor/art/kythera_build.py",
                      f"// Ichor: {sp['dir']}, {sp['title']} (Act II, the awe pass). Porytiles-managed, built by\n"
                      "// tools/ichor/art/astyra_build.py")
        t = t.replace(f"// Ichor: {sp['dir']} ({sp['title']}), written by tools/ichor/art/kythera_build.py",
                      f"// Ichor: {sp['dir']} ({sp['title']}), written by tools/ichor/art/astyra_build.py")
        p.write_text(t)
    cfg = ROOT / "porytiles/tilesets" / sp["symbol"] / "config.yaml"
    if cfg.exists():
        cfg.write_text(cfg.read_text().replace("kythera_build.py", "astyra_build.py"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tileset", nargs="?", default="all")
    ap.add_argument("--no-compile", action="store_true")
    args = ap.parse_args()
    for n in (NAMES if args.tileset == "all" else [args.tileset]):
        build_one(n, not args.no_compile)


if __name__ == "__main__":
    main()
