#!/usr/bin/env python3
"""Write the walker concept prompts for every Ichor overworld character (STYLE.md §3.6).

Reads the character catalogs (design/phase1/SPRITES_npc.md and SPRITES_folk.md)
for each character's look and palette family, and every walker sheet in
graphics/object_events/pics/people/ichor/. Writes design/art/WALKER_PROMPTS.md
and design/art/walker_prompts.json, and, with --refs DIR, an 8x enlargement of
each current sheet to attach as an identity reference.

  python3 tools/ichor/art/walker_prompts.py [--refs playtest/walker_refs]
"""
import argparse
import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
SHEETS = ROOT / "graphics/object_events/pics/people/ichor"
PALS = ROOT / "graphics/object_events/palettes"
OUT_MD = ROOT / "design/art/WALKER_PROMPTS.md"
OUT_JSON = ROOT / "design/art/walker_prompts.json"

STYLE = (
    "Pokémon Emerald (Gen 3, Game Boy Advance) overworld character sprite sheet, true pixel art. "
    "A 3x3 grid of frames, each frame exactly 16x32 pixels, drawn at 8x so every pixel is an "
    "8x8 square (the whole image is 384x768). Row 1 faces down toward the viewer, row 2 faces up "
    "(seen from behind), row 3 faces left (side view). Column 1 stands still, column 2 walks with "
    "the left foot forward, column 3 walks with the right foot forward; the head stays level. "
    "Chibi Gen 3 proportions exactly like Emerald's townsfolk: {height} with the feet on the "
    "bottom row of every frame, a big head about half the height (about 11 pixels tall and 13 "
    "wide), two 1x2-pixel dark eyes in the front view, a short sturdy body. One continuous "
    "1-pixel dark outline, two flat tones per material lit from the top left, no texture noise, "
    "no anti-aliasing, no gradients. Use only these colors: {colors}. Solid flat magenta "
    "background (#F800F8) everywhere else: no grid lines, no text, no shadow."
)


def read_pal(name):
    v = list(map(int, (PALS / f"ichor_{name}.pal").read_text().split()[3:]))
    cols = [tuple(v[i:i + 3]) for i in range(0, len(v), 3)][1:16]
    return ", ".join("#%02X%02X%02X" % c for c in cols)


def catalogs():
    """{sheet stem: (palette family, look)} from the two catalog tables."""
    looks = {}
    npc = (ROOT / "design/phase1/SPRITES_npc.md").read_text()
    for m in re.finditer(r"^\| `OBJ_EVENT_GFX_ICHOR_\w+` \| `ichor/(\w+)\.png` \| (.+?) \|$", npc, re.M):
        looks[m.group(1)] = ("cast", m.group(2))
    folk = (ROOT / "design/phase1/SPRITES_folk.md").read_text()
    for m in re.finditer(r"^\| `OBJ_EVENT_GFX_ICHOR_\w+` \| `(\w+)\.png` \| (\w+) \| (.+?) \|", folk, re.M):
        looks[m.group(1)] = (m.group(2), m.group(3))
    return looks


def height_for(name, look):
    if name.startswith("kid") or "child-sized" in look.lower():
        return "a child about 16 pixels tall"
    if name.startswith("elder") or "elder" in look.lower():
        return "an elder about 20 pixels tall, slightly stooped,"
    return "an adult about 21 pixels tall"


def family_of(stem):
    """Fallback: the palette a sheet already embeds, matched against the family files."""
    pal = Image.open(SHEETS / f"{stem}.png").getpalette()[3:48]
    for fam in ("cast", "folk", "theoxenia", "wine"):
        path = PALS / f"ichor_{fam}.pal"
        if path.exists() and list(map(int, path.read_text().split()[6:51])) == pal:
            return fam
    return "folk"


def build():
    looks = catalogs()
    rows = []
    for sheet in sorted(SHEETS.glob("*.png")):
        stem = sheet.stem
        im = Image.open(sheet)
        frames = im.width // 16 if im.height == 32 else None
        fam, look = looks.get(stem, (family_of(stem), None))
        known = look is not None
        if not known:
            look = ("keep this character's existing costume, hair and colors exactly; the attached "
                    "reference is the current sprite enlarged, redraw it in the proportions above")
        who = stem.replace("_", " ").title()
        prompt = (STYLE.format(height=height_for(stem, look), colors=read_pal(fam))
                  + f" Character: {who}, an ancient Greek {('character' if known else 'figure')}: {look}.")
        rows.append({"name": stem, "palette": fam, "frames": frames, "from_catalog": known,
                     "file": f"walker_{stem}.png", "prompt": prompt})
    return rows


def write(rows, refs=None):
    OUT_JSON.write_text(json.dumps(rows, ensure_ascii=False, indent=1) + "\n")
    lines = [
        "# Walker concept prompts",
        "",
        "Generated by `tools/ichor/art/walker_prompts.py` from the character catalogs. "
        "The standard is `design/STYLE.md` §3.6.",
        "",
        "1. With each prompt, attach Theo's sheet (`graphics/object_events/pics/people/brendan/walking.png`, enlarged) "
        "as the proportion reference. For characters marked *reference*, also attach their own enlarged current sheet.",
        "2. Save each result as a PNG with the file name given, at the size it was generated.",
        "3. Put them in one folder and hand it back; `tools/ichor/art/walker_from_concept.py` builds them.",
        "",
    ]
    for r in rows:
        extra = "" if r["from_catalog"] else " · *reference: attach its current sheet*"
        special = "" if r["frames"] == 9 else f" · special sheet ({r['frames']} frames): keep its poses"
        lines += [f"## {r['name']} ({r['palette']} palette){extra}{special}", "",
                  f"→ `{r['file']}`", "", "```text", r["prompt"], "```", ""]
    OUT_MD.write_text("\n".join(lines))
    if refs:
        Path(refs).mkdir(parents=True, exist_ok=True)
        for r in rows:
            im = Image.open(SHEETS / f"{r['name']}.png").convert("RGBA")
            bg = Image.new("RGBA", im.size, (248, 0, 248, 255))
            bg.alpha_composite(im)
            bg.convert("RGB").resize((im.width * 8, im.height * 8), Image.NEAREST).save(
                Path(refs) / f"{r['name']}_current.png")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--refs", help="write 8x reference enlargements of the current sheets here")
    a = ap.parse_args()
    rows = build()
    write(rows, a.refs)
    print(f"{len(rows)} walkers ({sum(r['from_catalog'] for r in rows)} from the catalogs) -> "
          f"{OUT_MD.relative_to(ROOT)}")
