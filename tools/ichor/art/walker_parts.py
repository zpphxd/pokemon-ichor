"""Hand-drawn parts for the Gen 3 walkers (see walker_paint.py for the roles).

Every grid is 16 wide and placed at its start row; '.' leaves a pixel alone.
Heads sit on rows 12-21 (eyes on 19-20), bodies on rows 22-30 with the feet on
row 30; walker_paint adds the outline on row 31. A part given only for the
down view is mirrored for the back view where that makes sense, or omitted
where the thing can't be seen from behind.
"""


class T:
    """A part grid placed at a start row; '.' leaves the pixel alone."""

    def __init__(self, start, text):
        self.start = start
        self.rows = [r for r in text.strip("\n").split("\n")]
        for i, r in enumerate(self.rows):
            assert len(r) == 16, f"row {start + i} is {len(r)} wide: {r!r}"

    def mirror(self):
        t = T.__new__(T)
        t.start, t.rows = self.start, [r[::-1] for r in self.rows]
        return t


def phases(stand, a=None, b=None, mirror_b=True):
    """(stand, step A, step B); B defaults to A mirrored (down/up views)."""
    a = a or stand
    b = b or (a.mirror() if mirror_b else a)
    return (stand, a, b)


def same(t):
    """One grid for every phase."""
    return phases(t)


def sub(t, mapping):
    """A copy of a grid with roles swapped, e.g. a white beard from a dark one."""
    u = T.__new__(T)
    u.start = t.start
    u.rows = ["".join(mapping.get(c, c) for c in r) for r in t.rows]
    return u


def subp(p, mapping):
    return tuple(sub(t, mapping) for t in p)


def shift(t, dy):
    u = T.__new__(T)
    u.start, u.rows = t.start + dy, list(t.rows)
    return u


