# ── thin props (no outline; drawn last) ─────────────────────────────────────
def _pole(col, top, bottom, cap, body):
    rows = []
    for y in range(top, bottom + 1):
        ch = cap[y - top] if y - top < len(cap) else body
        row = ["."] * 16
        if isinstance(ch, str) and len(ch) == 1:
            row[col] = ch
        else:
            for dx, c in ch:
                if 0 <= col + dx < 16:
                    row[col + dx] = c
        rows.append("".join(row))
    return T(top, "\n".join(rows))


def _pole_views(cap, top=14, body="p", side_col=1):
    down = _pole(1, top, 30, cap, body)
    up = _pole(14, top, 30, [[(-dx, c) for dx, c in x] if isinstance(x, list) else x for x in cap], body)
    left = _pole(side_col, top, 30, cap, body)
    return {"down": same(down), "up": same(up), "left": same(left)}


